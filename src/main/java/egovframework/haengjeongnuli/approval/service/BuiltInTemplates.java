    /** 기본 16종 + 지출품의·지출결의·불용·보고 서식 (MoreTemplates) */
    static final List<T> ALL = java.util.stream.Stream.concat(BASE.stream(), MoreTemplates.build().stream()).toList();

    private final ApprovalTemplateMapper mapper;
    private final JdbcTemplate jdbc;

    public BuiltInTemplates(ApprovalTemplateMapper mapper, JdbcTemplate jdbc) {
        this.mapper = mapper;
        this.jdbc = jdbc;
    }

    @Override
    public void run(ApplicationArguments args) {
        for (T t : ALL) {
            Integer n = jdbc.queryForObject("SELECT COUNT(*) FROM APPROVAL_TEMPLATE WHERE OWNER_ID = ? AND NAME = ?", Integer.class, OWNER, t.name());
            if (n != null && n > 0) {
                continue; // 이미 넣었거나 관리자가 지운 서식
            }
            ApprovalTemplateVO v = new ApprovalTemplateVO();
            v.setTemplateId(mapper.nextId());
            v.setName(t.name());
            v.setScope("ALL");
            v.setOwnerId(OWNER);
            v.setOwnerName("행정누리 기본 서식");
            v.setDeptName(null);
            v.setKind(t.kind());
            v.setRetention(t.retention());
            v.setTitle(t.title());
            v.setBody(t.body().strip());
            v.setCreatedAt(LocalDateTime.now());
            mapper.insert(v);
        }
    }
