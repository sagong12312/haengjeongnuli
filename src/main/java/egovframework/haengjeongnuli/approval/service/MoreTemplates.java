    private static T goods(String name, String what, String account, String method, String[]... items) {
        StringBuilder b = new StringBuilder();
        b.append("1. ○○ 업무 추진에 필요한 ").append(what).append("을(를) 다음과 같이 구매하고자 합니다.").append(NL);
        b.append("  가. 구매 내역").append(NL);
        b.append("| 품명 | 규격 | 단위 | 수량 | 단가(원) | 금액(원) |").append(NL);
        for (String[] it : items) {
            b.append("| ").append(it[0]).append(" | ").append(it.length > 1 ? it[1] : "○○").append(" | ").append(it.length > 2 ? it[2] : "개")
                    .append(" | ○ | ○○ | ○○ |").append(NL);
        }
        b.append("| 합계 |  |  |  |  | ○○ |").append(NL);
        b.append("  나. 소요 예산: 금○○원(부가가치세 포함)").append(NL);
        b.append("  다. 예산 과목: ○○ / ").append(account).append(NL);
        b.append("  라. 구매 방법: ").append(method).append(NL);
        b.append("  마. 납품 기한·장소: 20○○. ○. ○.까지 / ○○과").append(NL);
        b.append("2. 납품 후 검수를 거쳐 대금을 지급하고, 취득한 물품은 물품대장에 등록하겠습니다.").append(NL).append(NL);
        b.append("붙임  1. 견적서 ○부.").append(NL).append("      2. 물품 규격서(사진) 1부.  끝.");
        return new T("[지출품의] " + name, "지출품의", "5년", name, b.toString());
    }

