-- 유해사이트 차단: 직원 업무용 PC 에 까는 차단 스크립트의 도메인 목록과 거르는 DNS (한 번만 실행)
CREATE TABLE SITE_BLOCK_RULE (
    DOMAIN       VARCHAR2(253 CHAR)  NOT NULL,
    CATEGORY     VARCHAR2(20 CHAR)   NOT NULL,
    MEMO         VARCHAR2(200 CHAR),
    ADDED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    ADDED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_SITE_BLOCK_RULE PRIMARY KEY (DOMAIN)
);
CREATE TABLE SITE_BLOCK_CONF (
    CONF_ID      NUMBER(1)           NOT NULL,
    DNS_MODE     VARCHAR2(10 CHAR)   NOT NULL,
    DNS1         VARCHAR2(45 CHAR),
    DNS2         VARCHAR2(45 CHAR),
    APP_ID       NUMBER(19),
    VERSION      NUMBER(9)           NOT NULL,
    UPDATED_BY   VARCHAR2(50 CHAR)   NOT NULL,
    UPDATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_SITE_BLOCK_CONF PRIMARY KEY (CONF_ID)
);
-- 차단 항의(이의) 신청
CREATE SEQUENCE SEQ_SITE_BLOCK_APPEAL START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE SITE_BLOCK_APPEAL (
    APPEAL_ID    NUMBER(19)          NOT NULL,
    DOMAIN       VARCHAR2(253 CHAR)  NOT NULL,
    LOGIN_ID     VARCHAR2(50 CHAR)   NOT NULL,
    USER_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR),
    REASON       VARCHAR2(1000 CHAR) NOT NULL,
    STATUS       VARCHAR2(10 CHAR)   NOT NULL,
    ANSWER       VARCHAR2(500 CHAR),
    CREATED_AT   TIMESTAMP           NOT NULL,
    DECIDED_BY   VARCHAR2(50 CHAR),
    DECIDED_AT   TIMESTAMP,
    CONSTRAINT PK_SITE_BLOCK_APPEAL PRIMARY KEY (APPEAL_ID)
);
CREATE INDEX IX_SITE_BLOCK_APPEAL ON SITE_BLOCK_APPEAL (STATUS, CREATED_AT);
