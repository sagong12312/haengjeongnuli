-- 업무 지원 기능 (한 번만 실행)

CREATE TABLE WORK_LOG (
    LOG_ID       NUMBER(19)          NOT NULL,
    LOGIN_ID     VARCHAR2(50 CHAR)   NOT NULL,
    USER_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR),
    WORK_DATE    DATE                NOT NULL,
    BODY         VARCHAR2(1300 CHAR) NOT NULL,
    UPDATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_WORK_LOG PRIMARY KEY (LOG_ID),
    CONSTRAINT UK_WORK_LOG UNIQUE (LOGIN_ID, WORK_DATE)
);
CREATE TABLE DEPT_EVENT (
    EVENT_ID     NUMBER(19)          NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    EVENT_DATE   DATE                NOT NULL,
    TITLE        VARCHAR2(200 CHAR)  NOT NULL,
    CREATED_BY   VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_NAME VARCHAR2(100 CHAR)  NOT NULL,
    CREATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_DEPT_EVENT PRIMARY KEY (EVENT_ID)
);
CREATE TABLE COOP_REQ (
    REQ_ID       NUMBER(19)          NOT NULL,
    FROM_ID      VARCHAR2(50 CHAR)   NOT NULL,
    FROM_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    FROM_DEPT    VARCHAR2(100 CHAR),
    TO_DEPT      VARCHAR2(100 CHAR)  NOT NULL,
    TITLE        VARCHAR2(200 CHAR)  NOT NULL,
    BODY         VARCHAR2(1300 CHAR) NOT NULL,
    DUE_ON       DATE                NOT NULL,
    STATUS       VARCHAR2(10 CHAR)   NOT NULL,
    REPLY        VARCHAR2(1300 CHAR),
    REPLIED_BY   VARCHAR2(100 CHAR),
    REPLIED_AT   TIMESTAMP,
    REMINDED_YN  CHAR(1)             DEFAULT 'N' NOT NULL,
    CREATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_COOP_REQ PRIMARY KEY (REQ_ID)
);
CREATE TABLE MEETING_MINUTES (
    MIN_ID       NUMBER(19)          NOT NULL,
    TITLE        VARCHAR2(200 CHAR)  NOT NULL,
    MEET_DATE    DATE                NOT NULL,
    ATTENDEES    VARCHAR2(1000 CHAR),
    BODY         VARCHAR2(1300 CHAR) NOT NULL,
    DECISIONS    VARCHAR2(1300 CHAR),
    WRITER_ID    VARCHAR2(50 CHAR)   NOT NULL,
    WRITER_NAME  VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR),
    CREATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_MEETING_MINUTES PRIMARY KEY (MIN_ID)
);
CREATE TABLE CALL_LOG (
    CALL_ID      NUMBER(19)          NOT NULL,
    CALLED_AT    TIMESTAMP           NOT NULL,
    CALLER_NAME  VARCHAR2(100 CHAR),
    CALLER_PHONE VARCHAR2(20 CHAR),
    TOPIC        VARCHAR2(200 CHAR)  NOT NULL,
    SUMMARY      VARCHAR2(1300 CHAR),
    RESULT       VARCHAR2(10 CHAR)   NOT NULL,
    STAFF_ID     VARCHAR2(50 CHAR)   NOT NULL,
    STAFF_NAME   VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR),
    CONSTRAINT PK_CALL_LOG PRIMARY KEY (CALL_ID)
);
CREATE TABLE VISITOR_LOG (
    VISIT_ID     NUMBER(19)          NOT NULL,
    VISITOR_NAME VARCHAR2(100 CHAR)  NOT NULL,
    VISITOR_PHONE VARCHAR2(20 CHAR),
    ORG_NAME     VARCHAR2(100 CHAR),
    PURPOSE      VARCHAR2(200 CHAR)  NOT NULL,
    HOST_ID      VARCHAR2(50 CHAR)   NOT NULL,
    HOST_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    IN_AT        TIMESTAMP           NOT NULL,
    OUT_AT       TIMESTAMP,
    PURGED_YN    CHAR(1)             DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_VISITOR_LOG PRIMARY KEY (VISIT_ID)
);
CREATE TABLE LOST_ITEM (
    ITEM_ID      NUMBER(19)          NOT NULL,
    FOUND_AT     TIMESTAMP           NOT NULL,
    PLACE        VARCHAR2(200 CHAR)  NOT NULL,
    ITEM_DESC    VARCHAR2(300 CHAR)  NOT NULL,
    FINDER       VARCHAR2(100 CHAR),
    STORE_PLACE  VARCHAR2(200 CHAR)  NOT NULL,
    STATUS       VARCHAR2(10 CHAR)   NOT NULL,
    OWNER_NAME   VARCHAR2(100 CHAR),
    HANDLED_AT   TIMESTAMP,
    HANDLED_BY   VARCHAR2(100 CHAR),
    CREATED_BY   VARCHAR2(50 CHAR)   NOT NULL,
    REMINDED_YN  CHAR(1)             DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_LOST_ITEM PRIMARY KEY (ITEM_ID)
);
CREATE TABLE INFO_REQ (
    REQ_ID       NUMBER(19)          NOT NULL,
    RECEIPT_NO   VARCHAR2(20 CHAR)   NOT NULL,
    REQUESTER    VARCHAR2(100 CHAR)  NOT NULL,
    CONTACT      VARCHAR2(100 CHAR),
    CONTENT      VARCHAR2(1300 CHAR) NOT NULL,
    RECEIVED_ON  DATE                NOT NULL,
    DUE_ON       DATE                NOT NULL,
    EXTENDED_YN  CHAR(1)             DEFAULT 'N' NOT NULL,
    EXTEND_REASON VARCHAR2(300 CHAR),
    DEPT_NAME    VARCHAR2(100 CHAR),
    ASSIGNEE_ID  VARCHAR2(50 CHAR),
    STATUS       VARCHAR2(10 CHAR)   NOT NULL,
    DECISION     VARCHAR2(10 CHAR),
    DECISION_ON  DATE,
    DECISION_NOTE VARCHAR2(1000 CHAR),
    CREATED_BY   VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_INFO_REQ PRIMARY KEY (REQ_ID),
    CONSTRAINT UK_INFO_REQ_NO UNIQUE (RECEIPT_NO)
);
CREATE TABLE SUPPLY_ITEM (
    ITEM_ID      NUMBER(19)          NOT NULL,
    NAME         VARCHAR2(100 CHAR)  NOT NULL,
    UNIT         VARCHAR2(20 CHAR)   NOT NULL,
