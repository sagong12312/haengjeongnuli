    CONSTRAINT PK_SUPPLY_REQ PRIMARY KEY (REQ_ID)
);
CREATE TABLE MANUAL_DOC (
    DOC_ID       NUMBER(19)          NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR),
