-- 기관 정보, 시행문 발송 기록 (한 번만 실행)
-- 기관 정보
CREATE TABLE ORG_SETTING (
    SETTING_KEY    VARCHAR2(50 CHAR)    NOT NULL,
    SETTING_VALUE  VARCHAR2(1000 CHAR),
    UPDATED_BY     VARCHAR2(50 CHAR),
    UPDATED_AT     TIMESTAMP,
    CONSTRAINT PK_ORG_SETTING PRIMARY KEY (SETTING_KEY)
);

-- 시행문 발송 기록
CREATE SEQUENCE SEQ_APPROVAL_DISPATCH START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE APPROVAL_DISPATCH (
    DISPATCH_ID      NUMBER(19)          NOT NULL,
    DOC_ID           NUMBER(19)          NOT NULL,
    RECEIVER         VARCHAR2(200 CHAR)  NOT NULL,
    METHOD           VARCHAR2(20 CHAR)   NOT NULL,
    NOTE             VARCHAR2(500 CHAR),
    DISPATCHED_BY    VARCHAR2(50 CHAR)   NOT NULL,
    DISPATCHED_NAME  VARCHAR2(100 CHAR)  NOT NULL,
    DISPATCHED_AT    TIMESTAMP           NOT NULL,
    CONSTRAINT PK_APPROVAL_DISPATCH PRIMARY KEY (DISPATCH_ID),
    CONSTRAINT FK_APPROVAL_DISPATCH_DOC FOREIGN KEY (DOC_ID) REFERENCES APPROVAL_DOC (DOC_ID)
);
CREATE INDEX IX_APPROVAL_DISPATCH ON APPROVAL_DISPATCH (DOC_ID);
