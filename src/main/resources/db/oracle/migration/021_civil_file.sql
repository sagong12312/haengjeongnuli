CREATE SEQUENCE SEQ_CIVIL_FILE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE CIVIL_FILE (
    FILE_ID        NUMBER(19)          NOT NULL,
    COMPLAINT_ID   NUMBER(19)          NOT NULL,
    ORIGINAL_NAME  VARCHAR2(255 CHAR)  NOT NULL,
    STORED_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    FILE_SIZE      NUMBER(19)          NOT NULL,
    UPLOADED_BY    VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_CIVIL_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_CIVIL_FILE FOREIGN KEY (COMPLAINT_ID) REFERENCES CIVIL_COMPLAINT (COMPLAINT_ID)
);
CREATE INDEX IX_CIVIL_FILE ON CIVIL_FILE (COMPLAINT_ID);
