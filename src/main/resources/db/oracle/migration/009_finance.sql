-- 이미 만든 Oracle / Tibero DB에 재정(예산 편성·집행, 세입) 테이블을 추가한다 (한 번만 실행)

-- ===== 재정 =====
-- 세입 담당 직원 표시 (세입 화면은 이 표시가 있는 직원만 연다)
ALTER TABLE USER_ACCOUNT ADD (REVENUE_YN CHAR(1) DEFAULT 'N');

-- 예산 과목 코드. CODE_TYPE: FUNC(기능별 분야·부문) / ITEM(성질별 목그룹·편성목·통계목) / REV(세입 장·관·항·목)
CREATE TABLE FIN_CODE (
    CODE_TYPE    VARCHAR2(10)   NOT NULL,
    CODE         VARCHAR2(10)   NOT NULL,
    CODE_NAME    VARCHAR2(100)  NOT NULL,
    PARENT_CODE  VARCHAR2(10),
    CODE_LEVEL   VARCHAR2(10)   NOT NULL,
    SORT_NO      NUMBER(5)      NOT NULL,
    CONSTRAINT PK_FIN_CODE PRIMARY KEY (CODE_TYPE, CODE)
);

-- 사업 구조: 정책사업 > 단위사업 > 세부사업 (자치단체가 설정)
CREATE SEQUENCE SEQ_FIN_PROGRAM START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIN_PROGRAM (
    PROG_ID      NUMBER(19)     NOT NULL,
    FISCAL_YEAR  NUMBER(4)      NOT NULL,
    PROG_LEVEL   VARCHAR2(10)   NOT NULL,
    PARENT_ID    NUMBER(19),
    PROG_TYPE    VARCHAR2(20),
    FUNC_CODE    VARCHAR2(10),
    PROG_NAME    VARCHAR2(200)  NOT NULL,
    DEPT_NAME    VARCHAR2(100),
    CREATED_BY   VARCHAR2(50)   NOT NULL,
    CREATED_AT   TIMESTAMP      NOT NULL,
    DELETED_YN   CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_FIN_PROGRAM PRIMARY KEY (PROG_ID)
);
CREATE INDEX IX_FIN_PROGRAM_YEAR ON FIN_PROGRAM (FISCAL_YEAR, PROG_LEVEL);

-- 예산 편성. KIND: EXP(세출, 세부사업 × 통계목) / REV(세입, 세입 목)
-- STATUS: DRAFT(작성 중) / REQUESTED(승인 요청) / APPROVED(승인) / REJECTED(반려)
CREATE SEQUENCE SEQ_FIN_BUDGET START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIN_BUDGET (
    BUDGET_ID      NUMBER(19)     NOT NULL,
    KIND           VARCHAR2(3)    NOT NULL,
    FISCAL_YEAR    NUMBER(4)      NOT NULL,
    DETAIL_ID      NUMBER(19),
    CODE           VARCHAR2(10)   NOT NULL,
    AMOUNT         NUMBER(15)     NOT NULL,
    BASIS          VARCHAR2(2000),
    STATUS         VARCHAR2(10)   NOT NULL,
    DEPT_NAME      VARCHAR2(100),
    REQUESTER_ID   VARCHAR2(50)   NOT NULL,
    REQUESTER_NAME VARCHAR2(100)  NOT NULL,
    REQUESTED_AT   TIMESTAMP,
    REVIEWER_ID    VARCHAR2(50),
    REVIEWER_NAME  VARCHAR2(100),
    REVIEWED_AT    TIMESTAMP,
    REVIEW_NOTE    VARCHAR2(1000),
    CREATED_AT     TIMESTAMP      NOT NULL,
    UPDATED_AT     TIMESTAMP,
    DELETED_YN     CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_FIN_BUDGET PRIMARY KEY (BUDGET_ID)
);
CREATE INDEX IX_FIN_BUDGET_YEAR ON FIN_BUDGET (KIND, FISCAL_YEAR, STATUS);
CREATE INDEX IX_FIN_BUDGET_DETAIL ON FIN_BUDGET (DETAIL_ID);

-- 집행(세출 지출)·수납(세입). KIND: EXP / REV
CREATE SEQUENCE SEQ_FIN_TXN START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIN_TXN (
    TXN_ID        NUMBER(19)     NOT NULL,
    KIND          VARCHAR2(3)    NOT NULL,
    FISCAL_YEAR   NUMBER(4)      NOT NULL,
    BUDGET_ID     NUMBER(19),
    CODE          VARCHAR2(10)   NOT NULL,
    TXN_DATE      DATE           NOT NULL,
    AMOUNT        NUMBER(15)     NOT NULL,
    PARTY         VARCHAR2(200),
    DESCRIPTION   VARCHAR2(500),
    DEPT_NAME     VARCHAR2(100),
    CREATED_BY    VARCHAR2(50)   NOT NULL,
    CREATED_NAME  VARCHAR2(100)  NOT NULL,
    CREATED_AT    TIMESTAMP      NOT NULL,
    CANCELLED_YN  CHAR(1)        DEFAULT 'N' NOT NULL,
    CANCELLED_BY  VARCHAR2(50),
    CANCELLED_AT  TIMESTAMP,
    CONSTRAINT PK_FIN_TXN PRIMARY KEY (TXN_ID)
);
CREATE INDEX IX_FIN_TXN_BUDGET ON FIN_TXN (BUDGET_ID);
CREATE INDEX IX_FIN_TXN_YEAR ON FIN_TXN (KIND, FISCAL_YEAR, CODE);
