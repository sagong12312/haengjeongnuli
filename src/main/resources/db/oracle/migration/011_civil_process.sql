-- 민원 처리 이력 (배정, 처리기간 연장, 진행상황 통지, 처리 완료)
CREATE SEQUENCE SEQ_CIVIL_HISTORY START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE CIVIL_HISTORY (
    HIST_ID       NUMBER(19)     NOT NULL,
    COMPLAINT_ID  NUMBER(19)     NOT NULL,
    ACTION        VARCHAR2(20)   NOT NULL,
    DETAIL        VARCHAR2(2000),
    ACTOR_ID      VARCHAR2(50)   NOT NULL,
    ACTOR_NAME    VARCHAR2(100)  NOT NULL,
    ACTED_AT      TIMESTAMP      NOT NULL,
    CONSTRAINT PK_CIVIL_HISTORY PRIMARY KEY (HIST_ID)
);
CREATE INDEX IX_CIVIL_HISTORY ON CIVIL_HISTORY (COMPLAINT_ID, HIST_ID);
