-- 민방위·외국인주민 (한 번만 실행)

-- 민방위 대원 명부·교육, 외국인주민 지원 대장 (주민등록번호·외국인등록번호는 받지 않는다)
CREATE SEQUENCE SEQ_CD_MEMBER START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CD_TRAINING START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_FOREIGN_RESIDENT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_FOREIGN_SUPPORT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE CD_MEMBER (
    MEMBER_ID      NUMBER(19)          NOT NULL,
    NAME           VARCHAR2(100 CHAR)  NOT NULL,
    BIRTH_DATE     DATE                NOT NULL,
    ADDRESS        VARCHAR2(300 CHAR)  NOT NULL,
    PHONE          VARCHAR2(20 CHAR),
    UNIT_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    JOINED_ON      DATE                NOT NULL,
    STATUS         VARCHAR2(10 CHAR)   NOT NULL,
    RELEASED_ON    DATE,
    RELEASE_REASON VARCHAR2(200 CHAR),
    PURGE_AFTER    DATE,
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_CD_MEMBER PRIMARY KEY (MEMBER_ID)
);
CREATE INDEX IX_CD_MEMBER ON CD_MEMBER (STATUS, UNIT_NAME);
CREATE TABLE CD_TRAINING (
    TRAINING_ID    NUMBER(19)          NOT NULL,
    TITLE          VARCHAR2(200 CHAR)  NOT NULL,
    HELD_ON        DATE                NOT NULL,
    PLACE          VARCHAR2(200 CHAR)  NOT NULL,
    HOURS          NUMBER(3)           NOT NULL,
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_CD_TRAINING PRIMARY KEY (TRAINING_ID)
);
CREATE TABLE CD_ATTEND (
    TRAINING_ID    NUMBER(19)          NOT NULL,
    MEMBER_ID      NUMBER(19)          NOT NULL,
    NOTIFIED_ON    DATE,
    RESULT         VARCHAR2(10 CHAR)   NOT NULL,
    NOTE           VARCHAR2(200 CHAR),
    CONSTRAINT PK_CD_ATTEND PRIMARY KEY (TRAINING_ID, MEMBER_ID),
    CONSTRAINT FK_CD_ATTEND_T FOREIGN KEY (TRAINING_ID) REFERENCES CD_TRAINING (TRAINING_ID),
    CONSTRAINT FK_CD_ATTEND_M FOREIGN KEY (MEMBER_ID) REFERENCES CD_MEMBER (MEMBER_ID)
);
CREATE TABLE FOREIGN_RESIDENT (
    RES_ID         NUMBER(19)          NOT NULL,
    NAME           VARCHAR2(100 CHAR)  NOT NULL,
    NATIONALITY    VARCHAR2(50 CHAR)   NOT NULL,
    BIRTH_DATE     DATE                NOT NULL,
    ADDRESS        VARCHAR2(300 CHAR),
    PHONE          VARCHAR2(20 CHAR),
    LANGUAGE       VARCHAR2(50 CHAR),
    STAY_STATUS    VARCHAR2(20 CHAR),
    CONSENT_ON     DATE                NOT NULL,
    STATUS         VARCHAR2(10 CHAR)   NOT NULL,
    ENDED_ON       DATE,
    END_REASON     VARCHAR2(200 CHAR),
    PURGE_AFTER    DATE,
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_FOREIGN_RESIDENT PRIMARY KEY (RES_ID)
);
CREATE TABLE FOREIGN_SUPPORT (
    SUPPORT_ID     NUMBER(19)          NOT NULL,
    RES_ID         NUMBER(19)          NOT NULL,
    SUPPORT_ON     DATE                NOT NULL,
    KIND           VARCHAR2(20 CHAR)   NOT NULL,
    CONTENT        VARCHAR2(1000 CHAR) NOT NULL,
    STAFF_NAME     VARCHAR2(100 CHAR)  NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_FOREIGN_SUPPORT PRIMARY KEY (SUPPORT_ID),
    CONSTRAINT FK_FOREIGN_SUPPORT FOREIGN KEY (RES_ID) REFERENCES FOREIGN_RESIDENT (RES_ID)
);
