-- 공유재산 대장, 관용차량 (운행일지·주유·정비)
CREATE SEQUENCE SEQ_PUBLIC_PROPERTY START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PROPERTY_USE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_VEHICLE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_VEHICLE_LOG START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_VEHICLE_COST START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE PUBLIC_PROPERTY (
    PROP_ID        NUMBER(19)          NOT NULL,
    PROP_NO        VARCHAR2(30 CHAR)   NOT NULL,
    PROP_KIND      VARCHAR2(10 CHAR)   NOT NULL,
    PROP_CLASS     VARCHAR2(10 CHAR)   NOT NULL,
    NAME           VARCHAR2(200 CHAR)  NOT NULL,
    LOCATION       VARCHAR2(300 CHAR)  NOT NULL,
    AREA           NUMBER(12,2),
    APPRAISED      NUMBER(15)          NOT NULL,
    ACQUIRED_ON    DATE                NOT NULL,
    DEPT_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    USE_PURPOSE    VARCHAR2(300 CHAR),
    STATUS         VARCHAR2(10 CHAR)   NOT NULL,
    DISPOSED_ON    DATE,
    DISPOSE_REASON VARCHAR2(500 CHAR),
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_PUBLIC_PROPERTY PRIMARY KEY (PROP_ID),
    CONSTRAINT UX_PUBLIC_PROPERTY_NO UNIQUE (PROP_NO)
);
CREATE TABLE PROPERTY_USE (
    USE_ID         NUMBER(19)          NOT NULL,
    PROP_ID        NUMBER(19)          NOT NULL,
    USE_TYPE       VARCHAR2(10 CHAR)   NOT NULL,
    USER_NAME      VARCHAR2(200 CHAR)  NOT NULL,
    PURPOSE        VARCHAR2(300 CHAR)  NOT NULL,
    START_DATE     DATE                NOT NULL,
    END_DATE       DATE                NOT NULL,
    ANNUAL_FEE     NUMBER(15)          NOT NULL,
    FEE_NOTE       VARCHAR2(300 CHAR),
    STATUS         VARCHAR2(10 CHAR)   NOT NULL,
    END_NOTE       VARCHAR2(300 CHAR),
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_PROPERTY_USE PRIMARY KEY (USE_ID),
    CONSTRAINT FK_PROPERTY_USE FOREIGN KEY (PROP_ID) REFERENCES PUBLIC_PROPERTY (PROP_ID)
);
CREATE INDEX IX_PROPERTY_USE ON PROPERTY_USE (PROP_ID, END_DATE);
CREATE TABLE VEHICLE (
    VEHICLE_ID     NUMBER(19)          NOT NULL,
    PLATE_NO       VARCHAR2(20 CHAR)   NOT NULL,
    MODEL          VARCHAR2(100 CHAR)  NOT NULL,
    VEHICLE_KIND   VARCHAR2(10 CHAR)   NOT NULL,
    FUEL           VARCHAR2(10 CHAR)   NOT NULL,
    DEPT_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    ACQUIRED_ON    DATE                NOT NULL,
    INSPECTION_DUE DATE,
    INSURANCE_DUE  DATE,
    ODOMETER       NUMBER(9)           NOT NULL,
    STATUS         VARCHAR2(10 CHAR)   NOT NULL,
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_VEHICLE PRIMARY KEY (VEHICLE_ID),
    CONSTRAINT UX_VEHICLE_PLATE UNIQUE (PLATE_NO)
);
CREATE TABLE VEHICLE_LOG (
    LOG_ID         NUMBER(19)          NOT NULL,
    VEHICLE_ID     NUMBER(19)          NOT NULL,
    DRIVER_ID      VARCHAR2(50 CHAR)   NOT NULL,
    DRIVER_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    PURPOSE        VARCHAR2(300 CHAR)  NOT NULL,
    DESTINATION    VARCHAR2(200 CHAR)  NOT NULL,
    START_AT       TIMESTAMP           NOT NULL,
    END_AT         TIMESTAMP           NOT NULL,
    START_KM       NUMBER(9)           NOT NULL,
    END_KM         NUMBER(9)           NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_VEHICLE_LOG PRIMARY KEY (LOG_ID),
    CONSTRAINT FK_VEHICLE_LOG FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLE (VEHICLE_ID)
);
CREATE INDEX IX_VEHICLE_LOG ON VEHICLE_LOG (VEHICLE_ID, START_AT);
CREATE TABLE VEHICLE_COST (
    COST_ID        NUMBER(19)          NOT NULL,
    VEHICLE_ID     NUMBER(19)          NOT NULL,
    COST_KIND      VARCHAR2(10 CHAR)   NOT NULL,
    DONE_ON        DATE                NOT NULL,
    AMOUNT         NUMBER(12)          NOT NULL,
    LITERS         NUMBER(8,2),
    ODOMETER       NUMBER(9),
    VENDOR         VARCHAR2(200 CHAR),
    NOTE           VARCHAR2(500 CHAR),
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_VEHICLE_COST PRIMARY KEY (COST_ID),
    CONSTRAINT FK_VEHICLE_COST FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLE (VEHICLE_ID)
);
CREATE INDEX IX_VEHICLE_COST ON VEHICLE_COST (VEHICLE_ID, DONE_ON);
