-- 위생 행정처분 대장 (식품위생법·공중위생관리법)
CREATE SEQUENCE SEQ_HYGIENE_SANCTION START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE HYGIENE_SANCTION (
    SANCTION_ID    NUMBER(19)          NOT NULL,
    SANCTION_NO    VARCHAR2(30 CHAR)   NOT NULL,
    BIZ_ID         NUMBER(19)          NOT NULL,
    LAW_NAME       VARCHAR2(30 CHAR)   NOT NULL,
    KIND           VARCHAR2(30 CHAR)   NOT NULL,
    VIOLATION      VARCHAR2(1000 CHAR) NOT NULL,
    BASIS          VARCHAR2(200 CHAR)  NOT NULL,
    DECIDED_ON     DATE                NOT NULL,
    START_DATE     DATE,
    END_DATE       DATE,
    AMOUNT         NUMBER(15),
    CHECK_ID       NUMBER(19),
    PUBLIC_YN      CHAR(1)             NOT NULL,
    STATUS         VARCHAR2(10 CHAR)   NOT NULL,
    CANCEL_REASON  VARCHAR2(500 CHAR),
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_NAME   VARCHAR2(100 CHAR)  NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_HYGIENE_SANCTION PRIMARY KEY (SANCTION_ID),
    CONSTRAINT UX_HYGIENE_SANCTION_NO UNIQUE (SANCTION_NO),
    CONSTRAINT FK_HYGIENE_SANCTION FOREIGN KEY (BIZ_ID) REFERENCES FOOD_BUSINESS (BIZ_ID)
);
CREATE INDEX IX_HYGIENE_SANCTION ON HYGIENE_SANCTION (BIZ_ID, DECIDED_ON);
