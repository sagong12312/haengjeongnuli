-- 보안 프로그램 설치 안내 (한 번만 실행)

-- 보안 프로그램 설치 안내와 직원별 설치 확인
CREATE SEQUENCE SEQ_SECURITY_APP START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE SECURITY_APP (
    APP_ID       NUMBER(19)          NOT NULL,
    NAME         VARCHAR2(100 CHAR)  NOT NULL,
    PURPOSE      VARCHAR2(300 CHAR)  NOT NULL,
    GUIDE        VARCHAR2(1300 CHAR),
    URL          VARCHAR2(500 CHAR),
    REQUIRED_YN  CHAR(1)             NOT NULL,
    VERSION      NUMBER(9)           NOT NULL,
    SORT_NO      NUMBER(5)           NOT NULL,
    USE_YN       CHAR(1)             NOT NULL,
    UPDATED_BY   VARCHAR2(50 CHAR)   NOT NULL,
    UPDATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_SECURITY_APP PRIMARY KEY (APP_ID)
);
CREATE TABLE SECURITY_APP_ACK (
    APP_ID       NUMBER(19)          NOT NULL,
    LOGIN_ID     VARCHAR2(50 CHAR)   NOT NULL,
    VERSION      NUMBER(9)           NOT NULL,
    ACKED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_SECURITY_APP_ACK PRIMARY KEY (APP_ID, LOGIN_ID),
    CONSTRAINT FK_SECURITY_APP_ACK FOREIGN KEY (APP_ID) REFERENCES SECURITY_APP (APP_ID)
);
