-- 내려받은 파일의 보이지 않는 워터마크 기록 (한 번만 실행)

CREATE TABLE DOWNLOAD_MARK (
    MARK_ID      NUMBER(19)          NOT NULL,
    MARK_CODE    VARCHAR2(16 CHAR)   NOT NULL,
    LOGIN_ID     VARCHAR2(50 CHAR)   NOT NULL,
    USER_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR),
    CLIENT_IP    VARCHAR2(64 CHAR),
    KIND         VARCHAR2(20 CHAR)   NOT NULL,
    REQ_PATH     VARCHAR2(300 CHAR),
    FILE_NAME    VARCHAR2(300 CHAR),
    REASON       VARCHAR2(200 CHAR),
    CREATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_DOWNLOAD_MARK PRIMARY KEY (MARK_ID),
    CONSTRAINT UK_DOWNLOAD_MARK UNIQUE (MARK_CODE)
);
CREATE INDEX IX_DOWNLOAD_MARK_AT ON DOWNLOAD_MARK (CREATED_AT);
CREATE SEQUENCE SEQ_DOWNLOAD_MARK START WITH 1 INCREMENT BY 1 NOCACHE;
