CREATE SEQUENCE SEQ_FIN_BUDGET_CHANGE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIN_BUDGET_CHANGE (
    CHANGE_ID       NUMBER(19)          NOT NULL,
    BUDGET_ID       NUMBER(19)          NOT NULL,
    CHANGE_TYPE     VARCHAR2(10 CHAR)   NOT NULL,
    ROUND_NO        NUMBER(2),
    CARRY_KIND      VARCHAR2(20 CHAR),
    DELTA           NUMBER(15)          NOT NULL,
    REASON          VARCHAR2(1000 CHAR) NOT NULL,
    STATUS          VARCHAR2(10 CHAR)   NOT NULL,
    REQUESTER_ID    VARCHAR2(50 CHAR)   NOT NULL,
    REQUESTER_NAME  VARCHAR2(100 CHAR)  NOT NULL,
    REQUESTED_AT    TIMESTAMP           NOT NULL,
    REVIEWER_ID     VARCHAR2(50 CHAR),
    REVIEWER_NAME   VARCHAR2(100 CHAR),
    REVIEWED_AT     TIMESTAMP,
    REVIEW_NOTE     VARCHAR2(1000 CHAR),
    NEW_BUDGET_ID   NUMBER(19),
    CONSTRAINT PK_FIN_BUDGET_CHANGE PRIMARY KEY (CHANGE_ID),
    CONSTRAINT FK_FIN_BUDGET_CHANGE FOREIGN KEY (BUDGET_ID) REFERENCES FIN_BUDGET (BUDGET_ID)
);
CREATE INDEX IX_FIN_BUDGET_CHANGE ON FIN_BUDGET_CHANGE (BUDGET_ID);
