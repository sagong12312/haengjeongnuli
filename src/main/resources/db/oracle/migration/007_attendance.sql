-- 출퇴근 기록. 하루에 한 줄 (처음 출근 시각, 마지막 퇴근 시각)
CREATE SEQUENCE SEQ_ATTENDANCE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE ATTENDANCE (
    ATT_ID      NUMBER(19)     NOT NULL,
    LOGIN_ID    VARCHAR2(50)   NOT NULL,
    USER_NAME   VARCHAR2(100)  NOT NULL,
    DEPT_NAME   VARCHAR2(100),
    WORK_DATE   DATE           NOT NULL,
    IN_AT       TIMESTAMP      NOT NULL,
    OUT_AT      TIMESTAMP,
    IN_IP       VARCHAR2(45),
    OUT_IP      VARCHAR2(45),
    CONSTRAINT PK_ATTENDANCE PRIMARY KEY (ATT_ID),
    CONSTRAINT UX_ATTENDANCE_DAY UNIQUE (LOGIN_ID, WORK_DATE)
);
CREATE INDEX IX_ATTENDANCE_DEPT ON ATTENDANCE (DEPT_NAME, WORK_DATE);
