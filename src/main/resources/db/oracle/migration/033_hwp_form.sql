CREATE SEQUENCE SEQ_HWP_FORM START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE HWP_FORM (
    FORM_ID        NUMBER(19)          NOT NULL,
    NAME           VARCHAR2(100 CHAR)  NOT NULL,
    CATEGORY       VARCHAR2(20 CHAR)   NOT NULL,
    ORIGINAL_NAME  VARCHAR2(255 CHAR)  NOT NULL,
    STORED_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    FILE_SIZE      NUMBER(19)          NOT NULL,
    FIELDS         VARCHAR2(1300 CHAR),
    FILLABLE_YN    CHAR(1)             NOT NULL,
    USE_YN         CHAR(1)             NOT NULL,
    UPLOADED_BY    VARCHAR2(50 CHAR)   NOT NULL,
    UPLOADED_AT    TIMESTAMP           NOT NULL,
    CONSTRAINT PK_HWP_FORM PRIMARY KEY (FORM_ID)
);
