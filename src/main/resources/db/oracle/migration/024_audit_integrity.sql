-- 접속기록 해시 연결, 점검 결과
CREATE SEQUENCE SEQ_AUDIT_REVIEW START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE AUDIT_CHAIN (
    CHAIN_ID     NUMBER(1)          NOT NULL,
    LAST_LOG_ID  NUMBER(19),
    LAST_HASH    VARCHAR2(64 CHAR),
    CONSTRAINT PK_AUDIT_CHAIN PRIMARY KEY (CHAIN_ID)
);
INSERT INTO AUDIT_CHAIN (CHAIN_ID) SELECT 1 FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM AUDIT_CHAIN WHERE CHAIN_ID = 1);
CREATE TABLE AUDIT_REVIEW (
    REVIEW_ID    NUMBER(19)          NOT NULL,
    PERIOD_FROM  DATE                NOT NULL,
    PERIOD_TO    DATE                NOT NULL,
    RESULT       VARCHAR2(20 CHAR)   NOT NULL,
    CHAIN_OK_YN  CHAR(1)             NOT NULL,
    NOTE         VARCHAR2(1300 CHAR),
    REVIEWED_BY  VARCHAR2(50 CHAR)   NOT NULL,
    REVIEWED_NAME VARCHAR2(100 CHAR) NOT NULL,
    REVIEWED_AT  TIMESTAMP           NOT NULL,
    CONSTRAINT PK_AUDIT_REVIEW PRIMARY KEY (REVIEW_ID)
);
COMMIT;
