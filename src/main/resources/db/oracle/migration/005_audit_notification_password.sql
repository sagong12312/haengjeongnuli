-- 접속·작업 기록
CREATE SEQUENCE SEQ_AUDIT_LOG START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE AUDIT_LOG (
    LOG_ID       NUMBER(19)      NOT NULL,
    OCCURRED_AT  TIMESTAMP       NOT NULL,
    ACTOR_ID     VARCHAR2(50),              -- 로그인 실패 등은 입력한 아이디
    ACTION       VARCHAR2(40)    NOT NULL,
    TARGET       VARCHAR2(200),
    DETAIL       VARCHAR2(1000),
    CLIENT_IP    VARCHAR2(64),
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IX_AUDIT_TIME ON AUDIT_LOG (OCCURRED_AT);
CREATE INDEX IX_AUDIT_ACTOR ON AUDIT_LOG (ACTOR_ID, OCCURRED_AT);

-- 알림
CREATE SEQUENCE SEQ_NOTIFICATION START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE NOTIFICATION (
    NOTI_ID      NUMBER(19)      NOT NULL,
    LOGIN_ID     VARCHAR2(50)    NOT NULL,  -- 받는 사람
    MESSAGE      VARCHAR2(500)   NOT NULL,
    LINK         VARCHAR2(300),
    CREATED_AT   TIMESTAMP       NOT NULL,
    READ_YN      CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_NOTIFICATION PRIMARY KEY (NOTI_ID)
);
CREATE INDEX IX_NOTI_USER ON NOTIFICATION (LOGIN_ID, READ_YN, CREATED_AT);
