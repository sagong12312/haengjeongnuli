-- ===== 업무 대장 =====
-- 사회복지 담당 직원 표시 (복지 신청 화면은 이 표시가 있는 직원만 연다)
ALTER TABLE USER_ACCOUNT ADD (WELFARE_YN CHAR(1) DEFAULT 'N');

-- 건축 인허가 대장. KIND: PERMIT(허가) / REPORT(신고). 착수기한: 허가 2년(공장 3년), 신고 1년 (건축법 제11조 제7항, 제14조 제5항)
CREATE SEQUENCE SEQ_BUILDING_CASE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE BUILDING_CASE (
    CASE_ID        NUMBER(19)     NOT NULL,
    KIND           VARCHAR2(10)   NOT NULL,
    RECEIPT_NO     VARCHAR2(20),
    OWNER_NAME     VARCHAR2(100)  NOT NULL,
    SITE           VARCHAR2(300)  NOT NULL,
    BUILDING_USE   VARCHAR2(100)  NOT NULL,
    FLOOR_AREA     NUMBER(12,2),
    FLOORS         NUMBER(4),
    FACTORY_YN     CHAR(1)        DEFAULT 'N' NOT NULL,
    DECIDED_ON     DATE           NOT NULL,
    START_DEADLINE DATE           NOT NULL,
    EXTENDED_YN    CHAR(1)        DEFAULT 'N' NOT NULL,
    STARTED_ON     DATE,
    STATUS         VARCHAR2(10)   NOT NULL,
    NOTE           VARCHAR2(1000),
    CREATED_BY     VARCHAR2(50)   NOT NULL,
    CREATED_AT     TIMESTAMP      NOT NULL,
    CONSTRAINT PK_BUILDING_CASE PRIMARY KEY (CASE_ID)
);

-- 식품 영업소 대장 (식품위생법 제37조 제4항 영업신고)
CREATE SEQUENCE SEQ_FOOD_BUSINESS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FOOD_BUSINESS (
    BIZ_ID        NUMBER(19)     NOT NULL,
    BIZ_NAME      VARCHAR2(200)  NOT NULL,
    OWNER_NAME    VARCHAR2(100)  NOT NULL,
    ADDRESS       VARCHAR2(300)  NOT NULL,
    BIZ_TYPE      VARCHAR2(50)   NOT NULL,
    REPORTED_ON   DATE           NOT NULL,
    RECEIPT_NO    VARCHAR2(20),
    STATUS        VARCHAR2(10)   NOT NULL,
    CLOSED_ON     DATE,
    CREATED_BY    VARCHAR2(50)   NOT NULL,
    CREATED_AT    TIMESTAMP      NOT NULL,
    CONSTRAINT PK_FOOD_BUSINESS PRIMARY KEY (BIZ_ID)
);

-- 위생 점검 (식품위생법 제22조 출입·검사)
CREATE SEQUENCE SEQ_HYGIENE_CHECK START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE HYGIENE_CHECK (
    CHECK_ID      NUMBER(19)     NOT NULL,
    BIZ_ID        NUMBER(19)     NOT NULL,
    CHECKED_ON    DATE           NOT NULL,
    RESULT        VARCHAR2(10)   NOT NULL,
    VIOLATION     VARCHAR2(1000),
    ACTION        VARCHAR2(30)   NOT NULL,
    INSPECTOR_ID  VARCHAR2(50)   NOT NULL,
    INSPECTOR     VARCHAR2(100)  NOT NULL,
    CREATED_AT    TIMESTAMP      NOT NULL,
    CONSTRAINT PK_HYGIENE_CHECK PRIMARY KEY (CHECK_ID)
);
CREATE INDEX IX_HYGIENE_CHECK_BIZ ON HYGIENE_CHECK (BIZ_ID, CHECKED_ON);

-- 기초생활보장 급여 신청 (국민기초생활 보장법 제21조 신청, 제26조 결정·통지)
-- STATUS: RECEIVED(접수) / SURVEY(조사 중) / GRANTED(지급 결정) / DENIED(부적합 결정) / WITHDRAWN(취하)
CREATE SEQUENCE SEQ_WELFARE_CASE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE WELFARE_CASE (
    CASE_ID          NUMBER(19)     NOT NULL,
    CASE_NO          VARCHAR2(20)   NOT NULL,
    APPLICANT_NAME   VARCHAR2(100)  NOT NULL,
    BIRTH_DATE       DATE,
    ADDRESS          VARCHAR2(300),
    PHONE            VARCHAR2(20),
    APPLIED_ON       DATE           NOT NULL,
    BENEFITS         VARCHAR2(200)  NOT NULL,
    DEADLINE         DATE           NOT NULL,
    EXTEND_REASON    VARCHAR2(500),
    STATUS           VARCHAR2(10)   NOT NULL,
    ASSIGNEE_ID      VARCHAR2(50),
    ASSIGNEE_NAME    VARCHAR2(100),
    SURVEY_NOTE      CLOB,
    GRANTED_BENEFITS VARCHAR2(200),
    DECISION_SUMMARY VARCHAR2(4000),
    BENEFIT_METHOD   VARCHAR2(500),
    BENEFIT_START    DATE,
    DECIDED_ON       DATE,
    NOTIFIED_ON      DATE,
    CREATED_BY       VARCHAR2(50)   NOT NULL,
    CREATED_AT       TIMESTAMP      NOT NULL,
    CONSTRAINT PK_WELFARE_CASE PRIMARY KEY (CASE_ID),
    CONSTRAINT UK_WELFARE_CASE_NO UNIQUE (CASE_NO)
);
CREATE INDEX IX_WELFARE_CASE_STATUS ON WELFARE_CASE (STATUS, DEADLINE);
