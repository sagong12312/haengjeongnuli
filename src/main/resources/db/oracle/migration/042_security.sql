-- 보안 강화 (한 번만 실행)
-- 보안: 2단계 인증(OTP), 비밀번호 재사용 금지
CREATE TABLE USER_OTP (
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    SECRET         VARCHAR2(64 CHAR)   NOT NULL,
    ENABLED_YN     CHAR(1)             DEFAULT 'N' NOT NULL,
    LAST_STEP      NUMBER(19)          DEFAULT 0 NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_USER_OTP PRIMARY KEY (LOGIN_ID)
);
CREATE TABLE PW_HISTORY (
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    PW_HASH        VARCHAR2(100 CHAR)  NOT NULL,
    CHANGED_AT     TIMESTAMP           NOT NULL
);
CREATE INDEX IX_PW_HISTORY ON PW_HISTORY (LOGIN_ID, CHANGED_AT);
