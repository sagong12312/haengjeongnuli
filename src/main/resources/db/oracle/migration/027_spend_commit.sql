-- 지출품의(지출원인행위)로 묶은 예산
CREATE SEQUENCE SEQ_FIN_COMMIT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIN_COMMIT (
    COMMIT_ID    NUMBER(19)          NOT NULL,
    DOC_ID       NUMBER(19)          NOT NULL,
    BUDGET_ID    NUMBER(19)          NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR),
    SPEND_TYPE   VARCHAR2(20 CHAR),
    TITLE        VARCHAR2(300 CHAR)  NOT NULL,
    AMOUNT       NUMBER(15)          NOT NULL,
    SPENT        NUMBER(15)          DEFAULT 0 NOT NULL,
    CLOSED_YN    CHAR(1)             DEFAULT 'N' NOT NULL,
    CLOSED_BY    VARCHAR2(50 CHAR),
    CLOSED_AT    TIMESTAMP,
    CLOSE_NOTE   VARCHAR2(500 CHAR),
    CREATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_FIN_COMMIT PRIMARY KEY (COMMIT_ID),
    CONSTRAINT UX_FIN_COMMIT_DOC UNIQUE (DOC_ID)
);
CREATE INDEX IX_FIN_COMMIT_BUDGET ON FIN_COMMIT (BUDGET_ID);
