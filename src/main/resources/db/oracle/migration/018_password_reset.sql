-- 비밀번호 분실 요청 (한 번만 실행)
-- 비밀번호 분실 요청
CREATE SEQUENCE SEQ_PASSWORD_RESET START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE PASSWORD_RESET_REQUEST (
    REQ_ID        NUMBER(19)          NOT NULL,
    LOGIN_ID      VARCHAR2(50 CHAR)   NOT NULL,
    USER_NAME     VARCHAR2(100 CHAR)  NOT NULL,
    CONTACT       VARCHAR2(100 CHAR),
    REQUEST_IP    VARCHAR2(50 CHAR),
    REQUESTED_AT  TIMESTAMP           NOT NULL,
    STATUS        VARCHAR2(10 CHAR)   NOT NULL,
    HANDLED_BY    VARCHAR2(50 CHAR),
    HANDLED_AT    TIMESTAMP,
    CONSTRAINT PK_PASSWORD_RESET_REQUEST PRIMARY KEY (REQ_ID)
);
CREATE INDEX IX_PW_RESET_STATUS ON PASSWORD_RESET_REQUEST (STATUS, REQUESTED_AT);
