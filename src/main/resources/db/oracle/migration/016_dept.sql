-- 부서(조직도) 테이블을 만들고, 직원 계정에 적힌 부서 이름을 옮긴다 (한 번만 실행)

-- 부서(조직도). 직원·처리과는 부서 이름으로 잇고, 이름은 바꾸지 않는다 (바뀌면 새로 만들고 옛 부서는 폐지)
CREATE SEQUENCE SEQ_DEPT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE DEPT (
    DEPT_ID     NUMBER(19)          NOT NULL,
    DEPT_NAME   VARCHAR2(100 CHAR)  NOT NULL,
    PARENT_ID   NUMBER(19),
    DEPT_CODE   VARCHAR2(20 CHAR),
    SORT_ORDER  NUMBER(5)           DEFAULT 0 NOT NULL,
    USE_YN      CHAR(1)             DEFAULT 'Y' NOT NULL,
    CREATED_AT  TIMESTAMP           NOT NULL,
    CLOSED_AT   TIMESTAMP,
    CONSTRAINT PK_DEPT PRIMARY KEY (DEPT_ID),
    CONSTRAINT UK_DEPT_NAME UNIQUE (DEPT_NAME)
);
-- 직원 계정에 이미 적힌 부서 이름을 부서 목록으로 옮긴다 (이미 있는 것은 건너뛴다)
INSERT INTO DEPT (DEPT_ID, DEPT_NAME, SORT_ORDER, USE_YN, CREATED_AT)
SELECT SEQ_DEPT.NEXTVAL, U.DEPT_NAME, 0, 'Y', CURRENT_TIMESTAMP
  FROM USER_ACCOUNT U
 WHERE U.DEPT_NAME IS NOT NULL
   AND U.USER_ID = (SELECT MIN(U2.USER_ID) FROM USER_ACCOUNT U2 WHERE U2.DEPT_NAME = U.DEPT_NAME)
   AND NOT EXISTS (SELECT 1 FROM DEPT D WHERE D.DEPT_NAME = U.DEPT_NAME);

COMMIT;
