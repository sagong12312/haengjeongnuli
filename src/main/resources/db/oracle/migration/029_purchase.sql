-- 구매: 구매 건, 견적, 검수(검사), 물품대장
CREATE SEQUENCE SEQ_PURCHASE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PUR_QUOTE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PUR_INSPECTION START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ASSET START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE PURCHASE (
    PURCHASE_ID      NUMBER(19)          NOT NULL,
    PUR_NO           VARCHAR2(30 CHAR)   NOT NULL,
    PUR_YEAR         NUMBER(4)           NOT NULL,
    TITLE            VARCHAR2(300 CHAR)  NOT NULL,
    PUR_TYPE         VARCHAR2(10 CHAR)   NOT NULL,
    DEPT_NAME        VARCHAR2(100 CHAR)  NOT NULL,
    BUDGET_ID        NUMBER(19),
    ESTIMATED_AMOUNT NUMBER(15)          NOT NULL,
    STATUS           VARCHAR2(10 CHAR)   NOT NULL,
    SELECTED_QUOTE_ID NUMBER(19),
    SELECT_REASON    VARCHAR2(500 CHAR),
    NOTE             VARCHAR2(1000 CHAR),
    CREATED_BY       VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_NAME     VARCHAR2(100 CHAR)  NOT NULL,
    CREATED_AT       TIMESTAMP           NOT NULL,
    CANCELED_AT      TIMESTAMP,
    CANCEL_REASON    VARCHAR2(500 CHAR),
    CONSTRAINT PK_PURCHASE PRIMARY KEY (PURCHASE_ID),
    CONSTRAINT UX_PURCHASE_NO UNIQUE (PUR_NO)
);
CREATE INDEX IX_PURCHASE_DEPT ON PURCHASE (DEPT_NAME, PUR_YEAR);
CREATE TABLE PUR_QUOTE (
    QUOTE_ID       NUMBER(19)          NOT NULL,
    PURCHASE_ID    NUMBER(19)          NOT NULL,
    VENDOR         VARCHAR2(200 CHAR)  NOT NULL,
    BIZ_NO         VARCHAR2(20 CHAR),
    AMOUNT         NUMBER(15)          NOT NULL,
    QUOTE_DATE     DATE                NOT NULL,
    NOTE           VARCHAR2(500 CHAR),
    ORIGINAL_NAME  VARCHAR2(255 CHAR),
    STORED_NAME    VARCHAR2(100 CHAR),
    FILE_SIZE      NUMBER(19),
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_PUR_QUOTE PRIMARY KEY (QUOTE_ID),
    CONSTRAINT FK_PUR_QUOTE FOREIGN KEY (PURCHASE_ID) REFERENCES PURCHASE (PURCHASE_ID)
);
CREATE INDEX IX_PUR_QUOTE ON PUR_QUOTE (PURCHASE_ID);
CREATE TABLE PUR_INSPECTION (
    INSP_ID          NUMBER(19)          NOT NULL,
    PURCHASE_ID      NUMBER(19)          NOT NULL,
    NOTIFIED_DATE    DATE                NOT NULL,
    INSPECTED_DATE   DATE                NOT NULL,
    RESULT           VARCHAR2(10 CHAR)   NOT NULL,
    NOTE             VARCHAR2(1000 CHAR),
    INSPECTOR_ID     VARCHAR2(50 CHAR)   NOT NULL,
    INSPECTOR_NAME   VARCHAR2(100 CHAR)  NOT NULL,
    CREATED_AT       TIMESTAMP           NOT NULL,
    CONSTRAINT PK_PUR_INSPECTION PRIMARY KEY (INSP_ID),
    CONSTRAINT FK_PUR_INSPECTION FOREIGN KEY (PURCHASE_ID) REFERENCES PURCHASE (PURCHASE_ID)
);
CREATE INDEX IX_PUR_INSPECTION ON PUR_INSPECTION (PURCHASE_ID);
CREATE TABLE ASSET (
    ASSET_ID         NUMBER(19)          NOT NULL,
    ASSET_NO         VARCHAR2(30 CHAR)   NOT NULL,
    NAME             VARCHAR2(200 CHAR)  NOT NULL,
    SPEC             VARCHAR2(300 CHAR),
    QUANTITY         NUMBER(9)           NOT NULL,
    UNIT_PRICE       NUMBER(15)          NOT NULL,
    ACQUIRED_DATE    DATE                NOT NULL,
    PURCHASE_ID      NUMBER(19),
    DEPT_NAME        VARCHAR2(100 CHAR)  NOT NULL,
    LOCATION         VARCHAR2(200 CHAR),
    USER_NAME        VARCHAR2(100 CHAR),
    STATUS           VARCHAR2(10 CHAR)   NOT NULL,
    LAST_CHECKED_AT  DATE,
    LAST_CHECKED_BY  VARCHAR2(100 CHAR),
    DISPOSED_AT      DATE,
    DISPOSE_REASON   VARCHAR2(500 CHAR),
    CREATED_BY       VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT       TIMESTAMP           NOT NULL,
    CONSTRAINT PK_ASSET PRIMARY KEY (ASSET_ID),
    CONSTRAINT UX_ASSET_NO UNIQUE (ASSET_NO)
);
CREATE INDEX IX_ASSET_DEPT ON ASSET (DEPT_NAME, STATUS);
