-- 증명 발급대장, 계약대장
CREATE SEQUENCE SEQ_CERT_ISSUE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CONTRACT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE CERT_ISSUE (
    ISSUE_ID        NUMBER(19)          NOT NULL,
    ISSUE_NO        VARCHAR2(20 CHAR)   NOT NULL,
    ISSUE_YEAR      NUMBER(4)           NOT NULL,
    CERT_TYPE       VARCHAR2(50 CHAR)   NOT NULL,
    APPLICANT_NAME  VARCHAR2(100 CHAR)  NOT NULL,
    APPLICANT_TYPE  VARCHAR2(20 CHAR)   NOT NULL,
    PURPOSE         VARCHAR2(200 CHAR),
    COPIES          NUMBER(3)           NOT NULL,
    FEE             NUMBER(9)           NOT NULL,
    EXEMPT_REASON   VARCHAR2(200 CHAR),
    ID_CHECKED_YN   CHAR(1)             NOT NULL,
    DEPT_NAME       VARCHAR2(100 CHAR),
    ISSUED_BY       VARCHAR2(50 CHAR)   NOT NULL,
    ISSUED_NAME     VARCHAR2(100 CHAR)  NOT NULL,
    ISSUED_AT       TIMESTAMP           NOT NULL,
    CONSTRAINT PK_CERT_ISSUE PRIMARY KEY (ISSUE_ID),
    CONSTRAINT UX_CERT_ISSUE_NO UNIQUE (ISSUE_NO)
);
CREATE INDEX IX_CERT_ISSUE_AT ON CERT_ISSUE (ISSUED_AT);
CREATE TABLE CONTRACT (
    CONTRACT_ID     NUMBER(19)          NOT NULL,
    CONTRACT_NO     VARCHAR2(30 CHAR)   NOT NULL,
    CONTRACT_YEAR   NUMBER(4)           NOT NULL,
    TITLE           VARCHAR2(300 CHAR)  NOT NULL,
    CONTRACT_KIND   VARCHAR2(10 CHAR)   NOT NULL,
    METHOD          VARCHAR2(20 CHAR)   NOT NULL,
    PRIVATE_REASON  VARCHAR2(500 CHAR),
    PARTY           VARCHAR2(200 CHAR)  NOT NULL,
    PARTY_BIZ_NO    VARCHAR2(20 CHAR),
    AMOUNT          NUMBER(15)          NOT NULL,
    DEPOSIT         NUMBER(15),
    CONTRACT_DATE   DATE                NOT NULL,
    START_DATE      DATE,
    END_DATE        DATE,
    BUDGET_ID       NUMBER(19),
    STATUS          VARCHAR2(10 CHAR)   NOT NULL,
    STATUS_NOTE     VARCHAR2(500 CHAR),
    DEPT_NAME       VARCHAR2(100 CHAR)  NOT NULL,
    CREATED_BY      VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    CREATED_AT      TIMESTAMP           NOT NULL,
    UPDATED_AT      TIMESTAMP,
    CONSTRAINT PK_CONTRACT PRIMARY KEY (CONTRACT_ID),
    CONSTRAINT UX_CONTRACT_NO UNIQUE (CONTRACT_NO)
);
CREATE INDEX IX_CONTRACT_DEPT ON CONTRACT (DEPT_NAME, CONTRACT_YEAR);
