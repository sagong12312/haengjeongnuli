-- 대결자 지정
CREATE SEQUENCE SEQ_APPROVAL_PROXY START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE APPROVAL_PROXY (
    PROXY_ID        NUMBER(19)          NOT NULL,
    OWNER_ID        VARCHAR2(50 CHAR)   NOT NULL,
    OWNER_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    PROXY_LOGIN_ID  VARCHAR2(50 CHAR)   NOT NULL,
    PROXY_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    START_DATE      DATE                NOT NULL,
    END_DATE        DATE                NOT NULL,
    REASON          VARCHAR2(100 CHAR)  NOT NULL,
    CREATED_AT      TIMESTAMP           NOT NULL,
    CANCELED_YN     CHAR(1)             DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_APPROVAL_PROXY PRIMARY KEY (PROXY_ID)
);
CREATE INDEX IX_APPROVAL_PROXY_OWNER ON APPROVAL_PROXY (OWNER_ID, START_DATE);
