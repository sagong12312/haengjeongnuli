-- 전자민원 공지사항·자주 묻는 질문, 공개 상담 공감
CREATE SEQUENCE SEQ_EP_NOTICE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EP_FAQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE EP_NOTICE (
    NOTICE_ID      NUMBER(19)          NOT NULL,
    TITLE          VARCHAR2(300 CHAR)  NOT NULL,
    CONTENT        CLOB                NOT NULL,
    PINNED_YN      CHAR(1)             DEFAULT 'N' NOT NULL,
    VIEW_COUNT     NUMBER(10)          DEFAULT 0 NOT NULL,
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    UPDATED_AT     TIMESTAMP,
    CONSTRAINT PK_EP_NOTICE PRIMARY KEY (NOTICE_ID)
);
CREATE TABLE EP_FAQ (
    FAQ_ID         NUMBER(19)          NOT NULL,
    CATEGORY       VARCHAR2(50 CHAR)   NOT NULL,
    QUESTION       VARCHAR2(500 CHAR)  NOT NULL,
    ANSWER         VARCHAR2(1300 CHAR) NOT NULL,
    SORT_ORDER     NUMBER(5)           DEFAULT 0 NOT NULL,
    USE_YN         CHAR(1)             DEFAULT 'Y' NOT NULL,
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_EP_FAQ PRIMARY KEY (FAQ_ID)
);
CREATE TABLE EP_LIKE (
    COMPLAINT_ID   NUMBER(19)          NOT NULL,
    VOTER          VARCHAR2(64 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_EP_LIKE PRIMARY KEY (COMPLAINT_ID, VOTER)
);
CREATE SEQUENCE SEQ_EP_MEMBER START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE EP_MEMBER (
    MEMBER_ID      NUMBER(19)          NOT NULL,
    LOGIN_ID       VARCHAR2(30 CHAR)   NOT NULL,
    PW_HASH        VARCHAR2(100 CHAR)  NOT NULL,
    NAME           VARCHAR2(100 CHAR)  NOT NULL,
    MOBILE         VARCHAR2(20 CHAR),
    EMAIL          VARCHAR2(200 CHAR),
    ADDRESS        VARCHAR2(500 CHAR),
    FAILS          NUMBER(3)           DEFAULT 0 NOT NULL,
    LOCKED_UNTIL   TIMESTAMP,
    CREATED_AT     TIMESTAMP           NOT NULL,
    LAST_LOGIN_AT  TIMESTAMP,
    PW_CHANGED_AT  TIMESTAMP           NOT NULL,
    CONSTRAINT PK_EP_MEMBER PRIMARY KEY (MEMBER_ID),
    CONSTRAINT UK_EP_MEMBER_LOGIN UNIQUE (LOGIN_ID)
);
CREATE INDEX IX_CIVIL_MEMBER ON CIVIL_COMPLAINT (MEMBER_ID);
