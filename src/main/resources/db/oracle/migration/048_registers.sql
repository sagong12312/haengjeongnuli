-- 행정누리 대장 (한 번만 실행)

CREATE TABLE REG_ENTRY (
    ENTRY_ID     NUMBER(19)          NOT NULL,
    REG_CODE     VARCHAR2(40 CHAR)   NOT NULL,
    SCOPE        VARCHAR2(10 CHAR)   NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR),
    OWNER_ID     VARCHAR2(50 CHAR)   NOT NULL,
    OWNER_NAME   VARCHAR2(100 CHAR)  NOT NULL,
    TITLE        VARCHAR2(300 CHAR)  NOT NULL,
    STATUS       VARCHAR2(40 CHAR)   NOT NULL,
    CLOSED_YN    CHAR(1)             DEFAULT 'N' NOT NULL,
    DUE_ON       DATE,
    AMOUNT       NUMBER(19),
    SEARCH_TEXT  VARCHAR2(1000 CHAR),
    DATA         CLOB,
    CREATED_AT   TIMESTAMP           NOT NULL,
    UPDATED_AT   TIMESTAMP           NOT NULL,
    UPDATED_BY   VARCHAR2(100 CHAR)  NOT NULL,
    DELETED_YN   CHAR(1)             DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_REG_ENTRY PRIMARY KEY (ENTRY_ID)
);
CREATE INDEX IX_REG_ENTRY_CODE ON REG_ENTRY (REG_CODE, DELETED_YN, DEPT_NAME);
CREATE INDEX IX_REG_ENTRY_DUE ON REG_ENTRY (DUE_ON, CLOSED_YN);
CREATE TABLE REG_HISTORY (
    HIST_ID      NUMBER(19)          NOT NULL,
    ENTRY_ID     NUMBER(19)          NOT NULL,
    ACTOR_ID     VARCHAR2(50 CHAR)   NOT NULL,
    ACTOR_NAME   VARCHAR2(100 CHAR)  NOT NULL,
    ACTION       VARCHAR2(40 CHAR)   NOT NULL,
    NOTE         VARCHAR2(500 CHAR),
    AT_TIME      TIMESTAMP           NOT NULL,
    CONSTRAINT PK_REG_HISTORY PRIMARY KEY (HIST_ID)
);
CREATE INDEX IX_REG_HISTORY ON REG_HISTORY (ENTRY_ID);
CREATE SEQUENCE SEQ_REG START WITH 1 INCREMENT BY 1 NOCACHE;
