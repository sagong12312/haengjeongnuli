ALTER TABLE USER_ACCOUNT ADD (RECORDS_MANAGER_YN CHAR(1) DEFAULT 'N');
ALTER TABLE DOC_REGISTRY ADD (CANCELED_YN CHAR(1) DEFAULT 'N' NOT NULL);

-- 등록정보 수정 이력
CREATE SEQUENCE SEQ_DOC_REGISTRY_FIX START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE DOC_REGISTRY_FIX (
    FIX_ID          NUMBER(19)          NOT NULL,
    REG_ID          NUMBER(19)          NOT NULL,
    FIELD_NAME      VARCHAR2(30 CHAR)   NOT NULL,
    OLD_VALUE       VARCHAR2(1000 CHAR),
    NEW_VALUE       VARCHAR2(1000 CHAR),
    REASON          VARCHAR2(500 CHAR)  NOT NULL,
    STATUS          VARCHAR2(10 CHAR)   NOT NULL,
    REQUESTED_BY    VARCHAR2(50 CHAR)   NOT NULL,
    REQUESTED_NAME  VARCHAR2(100 CHAR)  NOT NULL,
    REQUESTED_AT    TIMESTAMP           NOT NULL,
    CONFIRMED_BY    VARCHAR2(50 CHAR),
    CONFIRMED_NAME  VARCHAR2(100 CHAR),
    CONFIRMED_AT    TIMESTAMP,
    CONSTRAINT PK_DOC_REGISTRY_FIX PRIMARY KEY (FIX_ID),
    CONSTRAINT FK_DOC_REGISTRY_FIX FOREIGN KEY (REG_ID) REFERENCES DOC_REGISTRY (REG_ID)
);
CREATE INDEX IX_DOC_REGISTRY_FIX ON DOC_REGISTRY_FIX (REG_ID);
