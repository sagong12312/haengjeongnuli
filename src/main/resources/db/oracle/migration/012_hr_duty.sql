-- 복무 신청 (연가·병가·공가·특별휴가·출장·시간외근무). 결재는 전자결재 문서(DOC_ID)로 하고 상태는 그 문서를 따른다.
CREATE SEQUENCE SEQ_DUTY_REQUEST START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE DUTY_REQUEST (
    REQ_ID       NUMBER(19)     NOT NULL,
    LOGIN_ID     VARCHAR2(50)   NOT NULL,
    USER_NAME    VARCHAR2(100)  NOT NULL,
    DEPT_NAME    VARCHAR2(100),
    KIND         VARCHAR2(20)   NOT NULL,
    START_DATE   DATE           NOT NULL,
    END_DATE     DATE           NOT NULL,
    HALF_DAY     VARCHAR2(2),
    START_TIME   VARCHAR2(5),
    END_TIME     VARCHAR2(5),
    DAYS         NUMBER(5,1),
    HOURS        NUMBER(5,1),
    DESTINATION  VARCHAR2(200),
    REASON       VARCHAR2(1000) NOT NULL,
    DOC_ID       NUMBER(19)     NOT NULL,
    CREATED_AT   TIMESTAMP      NOT NULL,
    CONSTRAINT PK_DUTY_REQUEST PRIMARY KEY (REQ_ID)
);
CREATE INDEX IX_DUTY_REQUEST_USER ON DUTY_REQUEST (LOGIN_ID, START_DATE);
