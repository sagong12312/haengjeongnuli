-- 이상 요청 차단과 이의 신청
CREATE SEQUENCE SEQ_ABUSE_BLOCK START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ABUSE_APPEAL START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE ABUSE_BLOCK (
    BLOCK_ID     NUMBER(19)          NOT NULL,
    IP           VARCHAR2(64 CHAR)   NOT NULL,
    REASON       VARCHAR2(1000 CHAR) NOT NULL,
    BLOCKED_AT   TIMESTAMP           NOT NULL,
    UNTIL_AT     TIMESTAMP           NOT NULL,
    RELEASED_BY  VARCHAR2(50 CHAR),
    RELEASED_AT  TIMESTAMP,
    CONSTRAINT PK_ABUSE_BLOCK PRIMARY KEY (BLOCK_ID)
);
CREATE INDEX IX_ABUSE_BLOCK_IP ON ABUSE_BLOCK (IP, UNTIL_AT);
CREATE TABLE ABUSE_APPEAL (
    APPEAL_ID    NUMBER(19)          NOT NULL,
    BLOCK_ID     NUMBER(19)          NOT NULL,
    IP           VARCHAR2(64 CHAR)   NOT NULL,
    NAME         VARCHAR2(100 CHAR)  NOT NULL,
    CONTACT      VARCHAR2(100 CHAR),
    MESSAGE      VARCHAR2(1000 CHAR) NOT NULL,
    STATUS       VARCHAR2(10 CHAR)   NOT NULL,
    CREATED_AT   TIMESTAMP           NOT NULL,
    HANDLED_BY   VARCHAR2(50 CHAR),
    HANDLED_AT   TIMESTAMP,
    HANDLE_NOTE  VARCHAR2(500 CHAR),
    CONSTRAINT PK_ABUSE_APPEAL PRIMARY KEY (APPEAL_ID)
);
