CREATE SEQUENCE SEQ_TODO_ITEM START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_MESSAGE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_REPLY_TEMPLATE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_LOAN_ITEM START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_LOAN START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_SURVEY START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE TODO_ITEM (
    TODO_ID        NUMBER(19)          NOT NULL,
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    TITLE          VARCHAR2(200 CHAR)  NOT NULL,
    DUE_ON         DATE,
    DONE_YN        CHAR(1)             DEFAULT 'N' NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    DONE_AT        TIMESTAMP,
    CONSTRAINT PK_TODO_ITEM PRIMARY KEY (TODO_ID)
);
CREATE INDEX IX_TODO_ITEM ON TODO_ITEM (LOGIN_ID, DONE_YN);
CREATE TABLE FAVORITE_MENU (
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    PATH           VARCHAR2(200 CHAR)  NOT NULL,
    LABEL          VARCHAR2(100 CHAR)  NOT NULL,
    SORT_ORDER     NUMBER(5)           DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FAVORITE_MENU PRIMARY KEY (LOGIN_ID, PATH)
);
CREATE TABLE MESSAGE (
    MSG_ID         NUMBER(19)          NOT NULL,
    FROM_ID        VARCHAR2(50 CHAR)   NOT NULL,
    FROM_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    TO_ID          VARCHAR2(50 CHAR)   NOT NULL,
    TO_NAME        VARCHAR2(100 CHAR)  NOT NULL,
    BODY           VARCHAR2(1300 CHAR) NOT NULL,
    SENT_AT        TIMESTAMP           NOT NULL,
    READ_AT        TIMESTAMP,
    TO_DEL         CHAR(1)             DEFAULT 'N' NOT NULL,
    FROM_DEL       CHAR(1)             DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_MESSAGE PRIMARY KEY (MSG_ID)
);
CREATE INDEX IX_MESSAGE_TO ON MESSAGE (TO_ID, SENT_AT);
CREATE INDEX IX_MESSAGE_FROM ON MESSAGE (FROM_ID, SENT_AT);
CREATE TABLE WORK_DUTY (
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    DUTIES         VARCHAR2(500 CHAR)  NOT NULL,
    UPDATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_WORK_DUTY PRIMARY KEY (LOGIN_ID)
);
CREATE TABLE REPLY_TEMPLATE (
    TPL_ID         NUMBER(19)          NOT NULL,
    OWNER_ID       VARCHAR2(50 CHAR),
    DEPT_NAME      VARCHAR2(100 CHAR),
    TITLE          VARCHAR2(100 CHAR)  NOT NULL,
    BODY           VARCHAR2(1300 CHAR) NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_REPLY_TEMPLATE PRIMARY KEY (TPL_ID)
);
CREATE TABLE LOAN_ITEM (
    ITEM_ID        NUMBER(19)          NOT NULL,
    NAME           VARCHAR2(100 CHAR)  NOT NULL,
    PLACE          VARCHAR2(200 CHAR),
    USE_YN         CHAR(1)             DEFAULT 'Y' NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_LOAN_ITEM PRIMARY KEY (ITEM_ID)
);
CREATE TABLE LOAN (
    LOAN_ID        NUMBER(19)          NOT NULL,
    ITEM_ID        NUMBER(19)          NOT NULL,
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    USER_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    PURPOSE        VARCHAR2(200 CHAR)  NOT NULL,
    DUE_ON         DATE                NOT NULL,
    STATUS         VARCHAR2(10 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    RETURNED_AT    TIMESTAMP,
    CONSTRAINT PK_LOAN PRIMARY KEY (LOAN_ID),
    CONSTRAINT FK_LOAN_ITEM FOREIGN KEY (ITEM_ID) REFERENCES LOAN_ITEM (ITEM_ID)
);
CREATE INDEX IX_LOAN ON LOAN (ITEM_ID, STATUS);
CREATE TABLE SURVEY (
    SURVEY_ID      NUMBER(19)          NOT NULL,
    TITLE          VARCHAR2(200 CHAR)  NOT NULL,
    QUESTION       VARCHAR2(500 CHAR)  NOT NULL,
    OPTIONS        VARCHAR2(1000 CHAR) NOT NULL,
    CLOSES_ON      DATE                NOT NULL,
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_SURVEY PRIMARY KEY (SURVEY_ID)
);
CREATE TABLE SURVEY_VOTER (
    SURVEY_ID      NUMBER(19)          NOT NULL,
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    VOTED_AT       TIMESTAMP           NOT NULL,
    CONSTRAINT PK_SURVEY_VOTER PRIMARY KEY (SURVEY_ID, LOGIN_ID)
);
CREATE TABLE SURVEY_COUNT (
    SURVEY_ID      NUMBER(19)          NOT NULL,
    OPT_NO         NUMBER(2)           NOT NULL,
    CNT            NUMBER(10)          DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SURVEY_COUNT PRIMARY KEY (SURVEY_ID, OPT_NO)
);
