-- 기안 서식
CREATE SEQUENCE SEQ_APPROVAL_TEMPLATE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE APPROVAL_TEMPLATE (
    TEMPLATE_ID  NUMBER(19)          NOT NULL,
    NAME         VARCHAR2(100 CHAR)  NOT NULL,
    SCOPE        VARCHAR2(10 CHAR)   NOT NULL,
    OWNER_ID     VARCHAR2(50 CHAR)   NOT NULL,
    OWNER_NAME   VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME    VARCHAR2(100 CHAR),
    KIND         VARCHAR2(30 CHAR)   NOT NULL,
    RETENTION    VARCHAR2(20 CHAR),
    TITLE        VARCHAR2(300 CHAR),
    BODY         CLOB,
    CREATED_AT   TIMESTAMP           NOT NULL,
    DELETED_YN   CHAR(1)             DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_APPROVAL_TEMPLATE PRIMARY KEY (TEMPLATE_ID)
);
