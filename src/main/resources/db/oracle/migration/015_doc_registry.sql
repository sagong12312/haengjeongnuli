-- 이미 만든 Oracle / Tibero DB에 기록물 등록대장을 추가하고, 번호가 붙은 전자결재 문서를 옮긴다 (한 번만 실행)

-- ===== 기록물 등록대장 (공공기록물법 시행령 제20조) =====
-- REG_TYPE: PRODUCE(생산) / RECEIVE(접수). SOURCE: APPROVAL(전자결재) / MANUAL(직접 등록)
-- 등록번호는 처리과별 연도별 등록일련번호(DOC_REG_COUNTER)를 전자결재와 함께 쓴다. 등록정보는 고치거나 지우지 않는다.
CREATE SEQUENCE SEQ_DOC_REGISTRY START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE DOC_REGISTRY (
    REG_ID          NUMBER(19)          NOT NULL,
    REG_TYPE        VARCHAR2(10 CHAR)   NOT NULL,
    REG_NO          VARCHAR2(130 CHAR)  NOT NULL,
    REG_YEAR        NUMBER(4)           NOT NULL,
    DEPT_NAME       VARCHAR2(100 CHAR)  NOT NULL,
    TITLE           VARCHAR2(300 CHAR)  NOT NULL,
    REG_DATE        DATE                NOT NULL,
    COUNTERPART     VARCHAR2(200 CHAR),
    COUNTERPART_NO  VARCHAR2(100 CHAR),
    MEDIUM          VARCHAR2(20 CHAR)   NOT NULL,
    PAGES           NUMBER(5),
    RETENTION       VARCHAR2(20 CHAR),
    DISCLOSURE      VARCHAR2(20 CHAR)   NOT NULL,
    SOURCE          VARCHAR2(10 CHAR)   NOT NULL,
    DOC_ID          NUMBER(19),
    HANDLER_ID      VARCHAR2(50 CHAR),
    HANDLER_NAME    VARCHAR2(100 CHAR),
    NOTE            VARCHAR2(1000 CHAR),
    REGISTERED_BY   VARCHAR2(50 CHAR)   NOT NULL,
    REGISTERED_NAME VARCHAR2(100 CHAR)  NOT NULL,
    REGISTERED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_DOC_REGISTRY PRIMARY KEY (REG_ID),
    CONSTRAINT UX_DOC_REGISTRY_NO UNIQUE (REG_YEAR, REG_NO)
);
CREATE INDEX IX_DOC_REGISTRY_DEPT ON DOC_REGISTRY (DEPT_NAME, REG_YEAR);

-- 직접 등록한 문서의 전자 파일(스캔본 등)
CREATE SEQUENCE SEQ_DOC_REGISTRY_FILE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE DOC_REGISTRY_FILE (
    FILE_ID        NUMBER(19)          NOT NULL,
    REG_ID         NUMBER(19)          NOT NULL,
    ORIGINAL_NAME  VARCHAR2(255 CHAR)  NOT NULL,
    STORED_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    FILE_SIZE      NUMBER(19)          NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_DOC_REGISTRY_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_DOC_REGISTRY_FILE FOREIGN KEY (REG_ID) REFERENCES DOC_REGISTRY (REG_ID)
);
CREATE INDEX IX_DOC_REGISTRY_FILE ON DOC_REGISTRY_FILE (REG_ID);

-- 이미 번호가 붙은 전자결재 문서를 등록대장으로 옮긴다 (이미 옮긴 것은 건너뛴다)
INSERT INTO DOC_REGISTRY (REG_ID, REG_TYPE, REG_NO, REG_YEAR, DEPT_NAME, TITLE, REG_DATE, COUNTERPART, MEDIUM,
                          RETENTION, DISCLOSURE, SOURCE, DOC_ID, REGISTERED_BY, REGISTERED_NAME, REGISTERED_AT)
SELECT SEQ_DOC_REGISTRY.NEXTVAL, 'PRODUCE', D.DOC_NO, D.DOC_YEAR, NVL(D.DRAFTER_DEPT, '행정누리'), D.TITLE,
       TRUNC(D.COMPLETED_AT), D.RECEIVER, '전자문서', D.RETENTION, D.DISCLOSURE, 'APPROVAL', D.DOC_ID,
       D.DRAFTER_ID, D.DRAFTER_NAME, D.COMPLETED_AT
  FROM APPROVAL_DOC D
 WHERE D.DOC_NO IS NOT NULL AND D.COMPLETED_AT IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM DOC_REGISTRY R WHERE R.DOC_ID = D.DOC_ID AND R.REG_TYPE = 'PRODUCE');
INSERT INTO DOC_REGISTRY (REG_ID, REG_TYPE, REG_NO, REG_YEAR, DEPT_NAME, TITLE, REG_DATE, COUNTERPART, COUNTERPART_NO,
                          MEDIUM, RETENTION, DISCLOSURE, SOURCE, DOC_ID, REGISTERED_BY, REGISTERED_NAME, REGISTERED_AT)
SELECT SEQ_DOC_REGISTRY.NEXTVAL, 'RECEIVE', D.RECEIPT_NO, EXTRACT(YEAR FROM D.RECEIVED_AT), D.RECEIVER, D.TITLE,
       TRUNC(D.RECEIVED_AT), NVL(D.DRAFTER_DEPT, '행정누리'), D.DOC_NO, '전자문서', D.RETENTION, D.DISCLOSURE, 'APPROVAL',
       D.DOC_ID, D.RECEIVED_BY, NVL((SELECT U.USER_NAME FROM USER_ACCOUNT U WHERE U.LOGIN_ID = D.RECEIVED_BY), D.RECEIVED_BY),
       D.RECEIVED_AT
  FROM APPROVAL_DOC D
 WHERE D.RECEIPT_NO IS NOT NULL AND D.RECEIVED_AT IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM DOC_REGISTRY R WHERE R.DOC_ID = D.DOC_ID AND R.REG_TYPE = 'RECEIVE');

COMMIT;
