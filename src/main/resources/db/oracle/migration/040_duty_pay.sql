CREATE SEQUENCE SEQ_ATTEND_FIX START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE TRIP_REPORT (
    REQ_ID         NUMBER(19)          NOT NULL,
    REPORT         VARCHAR2(1300 CHAR) NOT NULL,
    FARE           NUMBER(12)          DEFAULT 0 NOT NULL,
    LODGING_PAID   NUMBER(12)          DEFAULT 0 NOT NULL,
    AMOUNT         NUMBER(12)          NOT NULL,
    DETAIL         VARCHAR2(1000 CHAR) NOT NULL,
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_TRIP_REPORT PRIMARY KEY (REQ_ID)
);
CREATE TABLE ATTEND_FIX (
    FIX_ID         NUMBER(19)          NOT NULL,
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    WORK_DATE      DATE                NOT NULL,
    IN_TIME        VARCHAR2(5 CHAR),
    OUT_TIME       VARCHAR2(5 CHAR),
    OUT_NEXT_DAY   CHAR(1)             DEFAULT 'N' NOT NULL,
    REASON         VARCHAR2(500 CHAR)  NOT NULL,
    DOC_ID         NUMBER(19)          NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_ATTEND_FIX PRIMARY KEY (FIX_ID)
);
CREATE INDEX IX_ATTEND_FIX ON ATTEND_FIX (LOGIN_ID, WORK_DATE);
CREATE TABLE WORK_SCHEDULE (
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    START_TIME     VARCHAR2(5 CHAR)    NOT NULL,
    END_TIME       VARCHAR2(5 CHAR)    NOT NULL,
    UPDATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    UPDATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_WORK_SCHEDULE PRIMARY KEY (LOGIN_ID)
);
CREATE TABLE HR_PAY_SETTING (
    SKEY           VARCHAR2(100 CHAR)  NOT NULL,
    SVALUE         VARCHAR2(200 CHAR)  NOT NULL,
    UPDATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    UPDATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_HR_PAY_SETTING PRIMARY KEY (SKEY)
);
