-- 공통 업무 (한 번만 실행)
-- 공통 업무: 회의실 예약, 당직, 주간 업무 보고, 업무 인계인수, 법정의무교육, 비상연락망
CREATE SEQUENCE SEQ_ROOM START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ROOM_RESV START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_DUTY_ROSTER START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_DUTY_SWAP START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_WEEKLY_REPORT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_HANDOVER START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EDU_COURSE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EDU_RECORD START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE ROOM (
    ROOM_ID        NUMBER(19)          NOT NULL,
    NAME           VARCHAR2(100 CHAR)  NOT NULL,
    PLACE          VARCHAR2(200 CHAR),
    CAPACITY       NUMBER(4),
    USE_YN         CHAR(1)             DEFAULT 'Y' NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_ROOM PRIMARY KEY (ROOM_ID),
    CONSTRAINT UK_ROOM_NAME UNIQUE (NAME)
);
CREATE TABLE ROOM_RESV (
    RESV_ID        NUMBER(19)          NOT NULL,
    ROOM_ID        NUMBER(19)          NOT NULL,
    RESV_DATE      DATE                NOT NULL,
    START_TIME     VARCHAR2(5 CHAR)    NOT NULL,
    END_TIME       VARCHAR2(5 CHAR)    NOT NULL,
    TITLE          VARCHAR2(200 CHAR)  NOT NULL,
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    USER_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME      VARCHAR2(100 CHAR),
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_ROOM_RESV PRIMARY KEY (RESV_ID),
    CONSTRAINT FK_ROOM_RESV FOREIGN KEY (ROOM_ID) REFERENCES ROOM (ROOM_ID)
);
CREATE INDEX IX_ROOM_RESV ON ROOM_RESV (ROOM_ID, RESV_DATE);
CREATE TABLE DUTY_ROSTER (
    ROSTER_ID      NUMBER(19)          NOT NULL,
    DUTY_DATE      DATE                NOT NULL,
    DUTY_TYPE      VARCHAR2(10 CHAR)   NOT NULL,
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    USER_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME      VARCHAR2(100 CHAR),
    LOG_TEXT       VARCHAR2(1300 CHAR),
    LOG_AT         TIMESTAMP,
    CREATED_BY     VARCHAR2(50 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_DUTY_ROSTER PRIMARY KEY (ROSTER_ID),
    CONSTRAINT UK_DUTY_ROSTER UNIQUE (DUTY_DATE, DUTY_TYPE)
);
CREATE INDEX IX_DUTY_ROSTER_USER ON DUTY_ROSTER (LOGIN_ID, DUTY_DATE);
CREATE TABLE DUTY_SWAP (
    SWAP_ID        NUMBER(19)          NOT NULL,
    ROSTER_ID      NUMBER(19)          NOT NULL,
    FROM_ID        VARCHAR2(50 CHAR)   NOT NULL,
    TO_ID          VARCHAR2(50 CHAR)   NOT NULL,
    BACK_ROSTER_ID NUMBER(19),
    REASON         VARCHAR2(300 CHAR)  NOT NULL,
    STATUS         VARCHAR2(10 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP           NOT NULL,
    DECIDED_AT     TIMESTAMP,
    CONSTRAINT PK_DUTY_SWAP PRIMARY KEY (SWAP_ID)
);
CREATE TABLE WEEKLY_REPORT (
    REP_ID         NUMBER(19)          NOT NULL,
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    USER_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME      VARCHAR2(100 CHAR),
    WEEK_START     DATE                NOT NULL,
    DONE_TEXT      VARCHAR2(1300 CHAR) NOT NULL,
    PLAN_TEXT      VARCHAR2(1300 CHAR) NOT NULL,
    ISSUE_TEXT     VARCHAR2(1000 CHAR),
    UPDATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_WEEKLY_REPORT PRIMARY KEY (REP_ID),
    CONSTRAINT UK_WEEKLY_REPORT UNIQUE (LOGIN_ID, WEEK_START)
);
CREATE INDEX IX_WEEKLY_REPORT_DEPT ON WEEKLY_REPORT (DEPT_NAME, WEEK_START);
CREATE TABLE HANDOVER (
    HO_ID          NUMBER(19)          NOT NULL,
    FROM_ID        VARCHAR2(50 CHAR)   NOT NULL,
    FROM_NAME      VARCHAR2(100 CHAR)  NOT NULL,
    TO_ID          VARCHAR2(50 CHAR)   NOT NULL,
    TO_NAME        VARCHAR2(100 CHAR)  NOT NULL,
    DEPT_NAME      VARCHAR2(100 CHAR),
    TITLE          VARCHAR2(200 CHAR)  NOT NULL,
    TASKS          VARCHAR2(1300 CHAR) NOT NULL,
    DOCS           VARCHAR2(1300 CHAR),
    NOTES          VARCHAR2(1300 CHAR),
    STATUS         VARCHAR2(10 CHAR)   NOT NULL,
    ACCEPT_NOTE    VARCHAR2(500 CHAR),
    CREATED_AT     TIMESTAMP           NOT NULL,
    ACCEPTED_AT    TIMESTAMP,
    CONSTRAINT PK_HANDOVER PRIMARY KEY (HO_ID)
);
CREATE TABLE EDU_COURSE (
    COURSE_ID      NUMBER(19)          NOT NULL,
    NAME           VARCHAR2(100 CHAR)  NOT NULL,
    HOURS          NUMBER(4,1)         NOT NULL,
    BASIS          VARCHAR2(200 CHAR),
    USE_YN         CHAR(1)             DEFAULT 'Y' NOT NULL,
    SORT_ORDER     NUMBER(5)           DEFAULT 0 NOT NULL,
    CONSTRAINT PK_EDU_COURSE PRIMARY KEY (COURSE_ID),
    CONSTRAINT UK_EDU_COURSE UNIQUE (NAME)
);
CREATE TABLE EDU_RECORD (
    REC_ID         NUMBER(19)          NOT NULL,
    COURSE_ID      NUMBER(19)          NOT NULL,
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    EDU_YEAR       NUMBER(4)           NOT NULL,
    DONE_ON        DATE                NOT NULL,
    HOURS          NUMBER(4,1)         NOT NULL,
    PROVIDER       VARCHAR2(100 CHAR),
    CREATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_EDU_RECORD PRIMARY KEY (REC_ID),
    CONSTRAINT FK_EDU_RECORD FOREIGN KEY (COURSE_ID) REFERENCES EDU_COURSE (COURSE_ID)
);
CREATE INDEX IX_EDU_RECORD ON EDU_RECORD (LOGIN_ID, EDU_YEAR);
CREATE TABLE EMERGENCY_CONTACT (
    LOGIN_ID       VARCHAR2(50 CHAR)   NOT NULL,
    MOBILE         VARCHAR2(20 CHAR)   NOT NULL,
    SHARE_YN       CHAR(1)             DEFAULT 'N' NOT NULL,
    UPDATED_AT     TIMESTAMP           NOT NULL,
    CONSTRAINT PK_EMERGENCY_CONTACT PRIMARY KEY (LOGIN_ID)
);
