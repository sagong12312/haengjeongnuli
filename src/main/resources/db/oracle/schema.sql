-- 행정누리 테이블 (Oracle / Tibero)
-- DBA가 운영 DB에 한 번 실행한다. 애플리케이션은 이 파일을 자동 실행하지 않는다.

-- 민원
CREATE SEQUENCE SEQ_CIVIL_COMPLAINT START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE CIVIL_COMPLAINT (
    COMPLAINT_ID     NUMBER(19)      NOT NULL,
    RECEIPT_NO       VARCHAR2(20)    NOT NULL,
    KIND             VARCHAR2(20)    NOT NULL,   -- LEGAL, QUERY, SUGGESTION, OTHER, GRIEVANCE
    LAW_INTERPRET_YN CHAR(1)         DEFAULT 'N' NOT NULL,
    LEGAL_AFFAIR     VARCHAR2(40),
    ROUTE            VARCHAR2(20)    NOT NULL,
    APPLICANT_NAME   VARCHAR2(100)   NOT NULL,
    MOBILE           VARCHAR2(20),
    HOME_PHONE       VARCHAR2(20),
    EMAIL            VARCHAR2(200),
    ADDRESS          VARCHAR2(500),
    NOTIFY_METHOD    VARCHAR2(20)    NOT NULL,
    TITLE            VARCHAR2(300)   NOT NULL,
    CONTENT          CLOB            NOT NULL,
    DEPT             VARCHAR2(100),
    ASSIGNEE         VARCHAR2(100),
    STATUS           VARCHAR2(20)    NOT NULL,   -- RECEIVED, IN_PROGRESS, DONE
    RECEIVED_AT      TIMESTAMP       NOT NULL,
    DEADLINE         DATE,
    DEADLINE_AT      TIMESTAMP,
    COMPLETED_AT     TIMESTAMP,
    REGISTER_ID      VARCHAR2(100)   NOT NULL,
    CONSTRAINT PK_CIVIL_COMPLAINT PRIMARY KEY (COMPLAINT_ID),
    CONSTRAINT UK_CIVIL_RECEIPT_NO UNIQUE (RECEIPT_NO)
);
CREATE INDEX IX_CIVIL_STATUS_DEADLINE ON CIVIL_COMPLAINT (STATUS, DEADLINE);

-- 게시판
CREATE SEQUENCE SEQ_BOARD_POST START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE BOARD_POST (
    POST_ID      NUMBER(19)     NOT NULL,
    BOARD_TYPE   VARCHAR2(20)   NOT NULL,   -- notice, suggest, archive
    TITLE        VARCHAR2(300)  NOT NULL,
    CONTENT      CLOB,
    CATEGORY     VARCHAR2(50),
    OPEN_SCOPE   VARCHAR2(20)   NOT NULL,
    PINNED_YN    CHAR(1)        DEFAULT 'N' NOT NULL,
    VIEW_COUNT   NUMBER(10)     DEFAULT 0 NOT NULL,
    WRITER       VARCHAR2(100)  NOT NULL,
    WRITER_DEPT  VARCHAR2(100),
    CREATED_AT   TIMESTAMP      NOT NULL,
    WRITER_ID    VARCHAR2(50),              -- 글쓴이 아이디 (삭제 권한 확인)
    DELETED_YN   CHAR(1)        DEFAULT 'N' NOT NULL,
    DELETED_AT   TIMESTAMP,
    DELETED_BY   VARCHAR2(50),
    UPDATED_AT   TIMESTAMP,
    UPDATED_BY   VARCHAR2(50),
    CONSTRAINT PK_BOARD_POST PRIMARY KEY (POST_ID)
);
CREATE INDEX IX_BOARD_TYPE_CREATED ON BOARD_POST (BOARD_TYPE, CREATED_AT);

-- 첨부파일 (게시판·자료실)
CREATE SEQUENCE SEQ_ATTACH_FILE START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE ATTACH_FILE (
    FILE_ID        NUMBER(19)     NOT NULL,
    POST_ID        NUMBER(19)     NOT NULL,
    ORIGINAL_NAME  VARCHAR2(255)  NOT NULL,
    STORED_NAME    VARCHAR2(100)  NOT NULL,   -- 서버에 저장한 이름 (무작위)
    FILE_SIZE      NUMBER(19)     NOT NULL,
    DOWNLOAD_COUNT NUMBER(10)     DEFAULT 0 NOT NULL,
    CREATED_AT     TIMESTAMP      NOT NULL,
    CONSTRAINT PK_ATTACH_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_ATTACH_FILE_POST FOREIGN KEY (POST_ID) REFERENCES BOARD_POST (POST_ID)
);
CREATE INDEX IX_ATTACH_FILE_POST ON ATTACH_FILE (POST_ID);

-- 직원 계정 (로그인)
CREATE SEQUENCE SEQ_USER_ACCOUNT START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE USER_ACCOUNT (
    USER_ID        NUMBER(19)     NOT NULL,
    LOGIN_ID       VARCHAR2(50)   NOT NULL,
    PASSWORD_HASH  VARCHAR2(200)  NOT NULL,   -- BCrypt
    USER_NAME      VARCHAR2(100)  NOT NULL,
    POSITION_NAME  VARCHAR2(50),
    DEPT_NAME      VARCHAR2(100),
    ROLE           VARCHAR2(20)   NOT NULL,   -- GENERAL, COUNTER, ADMIN
    ENABLED_YN     CHAR(1)        DEFAULT 'Y' NOT NULL,
    FAILED_COUNT   NUMBER(3)      DEFAULT 0 NOT NULL,
    LAST_LOGIN_AT  TIMESTAMP,
    CREATED_AT     TIMESTAMP      NOT NULL,
    PASSWORD_CHANGED_AT TIMESTAMP,            -- 비어 있으면 첫 로그인 때 변경
    CONSTRAINT PK_USER_ACCOUNT PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USER_LOGIN_ID UNIQUE (LOGIN_ID)
);

-- 부서 이동 기록
CREATE SEQUENCE SEQ_USER_DEPT_HISTORY START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE USER_DEPT_HISTORY (
    HISTORY_ID   NUMBER(19)     NOT NULL,
    USER_ID      NUMBER(19)     NOT NULL,
    FROM_DEPT    VARCHAR2(100),
    TO_DEPT      VARCHAR2(100),
    MOVED_AT     TIMESTAMP      NOT NULL,
    MOVED_BY     VARCHAR2(50)   NOT NULL,   -- 처리한 관리자 아이디
    CONSTRAINT PK_USER_DEPT_HISTORY PRIMARY KEY (HISTORY_ID),
    CONSTRAINT FK_DEPT_HISTORY_USER FOREIGN KEY (USER_ID) REFERENCES USER_ACCOUNT (USER_ID)
);

-- 댓글
CREATE SEQUENCE SEQ_BOARD_COMMENT START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE BOARD_COMMENT (
    COMMENT_ID   NUMBER(19)      NOT NULL,
    POST_ID      NUMBER(19)      NOT NULL,
    CONTENT      VARCHAR2(4000)  NOT NULL,
    WRITER       VARCHAR2(100)   NOT NULL,
    WRITER_ID    VARCHAR2(50)    NOT NULL,
    WRITER_DEPT  VARCHAR2(100),
    CREATED_AT   TIMESTAMP       NOT NULL,
    DELETED_YN   CHAR(1)         DEFAULT 'N' NOT NULL,
    DELETED_AT   TIMESTAMP,
    DELETED_BY   VARCHAR2(50),
    CONSTRAINT PK_BOARD_COMMENT PRIMARY KEY (COMMENT_ID),
    CONSTRAINT FK_COMMENT_POST FOREIGN KEY (POST_ID) REFERENCES BOARD_POST (POST_ID)
);
CREATE INDEX IX_COMMENT_POST ON BOARD_COMMENT (POST_ID);

-- 접속·작업 기록
CREATE SEQUENCE SEQ_AUDIT_LOG START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE AUDIT_LOG (
    LOG_ID       NUMBER(19)      NOT NULL,
    OCCURRED_AT  TIMESTAMP       NOT NULL,
    ACTOR_ID     VARCHAR2(50),              -- 로그인 실패 등은 입력한 아이디
    ACTION       VARCHAR2(40)    NOT NULL,
    TARGET       VARCHAR2(200),
    DETAIL       VARCHAR2(1000),
    CLIENT_IP    VARCHAR2(64),
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IX_AUDIT_TIME ON AUDIT_LOG (OCCURRED_AT);
CREATE INDEX IX_AUDIT_ACTOR ON AUDIT_LOG (ACTOR_ID, OCCURRED_AT);

-- 알림
CREATE SEQUENCE SEQ_NOTIFICATION START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE NOTIFICATION (
    NOTI_ID      NUMBER(19)      NOT NULL,
    LOGIN_ID     VARCHAR2(50)    NOT NULL,  -- 받는 사람
    MESSAGE      VARCHAR2(500)   NOT NULL,
    LINK         VARCHAR2(300),
    CREATED_AT   TIMESTAMP       NOT NULL,
    READ_YN      CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_NOTIFICATION PRIMARY KEY (NOTI_ID)
);
CREATE INDEX IX_NOTI_USER ON NOTIFICATION (LOGIN_ID, READ_YN, CREATED_AT);

-- 전자결재 문서. STATUS: DRAFT(임시저장) / PROG(진행 중) / DONE(완료) / REJECTED(반려)
-- 문서번호(DOC_NO)는 결재가 끝날 때 '기안부서-연도별 일련번호'로 붙인다.
CREATE SEQUENCE SEQ_APPROVAL_DOC START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE APPROVAL_DOC (
    DOC_ID           NUMBER(19)     NOT NULL,
    DOC_NO           VARCHAR2(130),
    DOC_YEAR         NUMBER(4),
    DOC_SEQ          NUMBER(10),
    KIND             VARCHAR2(30)   NOT NULL,
    RETENTION        VARCHAR2(20)   NOT NULL,
    DISCLOSURE       VARCHAR2(20)   NOT NULL,
    RESTRICT_REASONS VARCHAR2(50),
    RESTRICT_DETAIL  VARCHAR2(500),
    RECEIVER_TYPE    VARCHAR2(10)   NOT NULL,
    RECEIVER         VARCHAR2(200),
    VIA              VARCHAR2(200),
    REFERENCE_TO     VARCHAR2(200),
    SENDER           VARCHAR2(200),
    EFFECTIVE_DATE   DATE,
    TITLE            VARCHAR2(300)  NOT NULL,
    BODY             CLOB,
    STATUS           VARCHAR2(10)   NOT NULL,
    DRAFTER_ID       VARCHAR2(50)   NOT NULL,
    DRAFTER_NAME     VARCHAR2(100)  NOT NULL,
    DRAFTER_POSITION VARCHAR2(50),
    DRAFTER_DEPT     VARCHAR2(100),
    CREATED_AT       TIMESTAMP      NOT NULL,
    UPDATED_AT       TIMESTAMP,
    SUBMITTED_AT     TIMESTAMP,
    COMPLETED_AT     TIMESTAMP,
    RECEIVED_BY      VARCHAR2(50),
    RECEIVED_AT      TIMESTAMP,
    RECEIPT_NO       VARCHAR2(130),
    DELETED_YN       CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_APPROVAL_DOC PRIMARY KEY (DOC_ID),
    CONSTRAINT UX_APPROVAL_DOC_NO UNIQUE (DOC_YEAR, DOC_NO)
);
CREATE INDEX IX_APPROVAL_DOC_DRAFTER ON APPROVAL_DOC (DRAFTER_ID, STATUS);
CREATE INDEX IX_APPROVAL_DOC_RECEIVER ON APPROVAL_DOC (RECEIVER, STATUS);

-- 결재선. STATUS: WAIT(차례 전) / PENDING(결재할 차례) / APPROVED / REJECTED
CREATE SEQUENCE SEQ_APPROVAL_LINE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE APPROVAL_LINE (
    LINE_ID           NUMBER(19)     NOT NULL,
    DOC_ID            NUMBER(19)     NOT NULL,
    STEP_NO           NUMBER(2)      NOT NULL,
    ROLE              VARCHAR2(10)   NOT NULL,
    APPROVER_ID       VARCHAR2(50)   NOT NULL,
    APPROVER_NAME     VARCHAR2(100)  NOT NULL,
    APPROVER_POSITION VARCHAR2(50),
    APPROVER_DEPT     VARCHAR2(100),
    STATUS            VARCHAR2(10)   NOT NULL,
    OPINION           VARCHAR2(1000),
    ACTED_AT          TIMESTAMP,
    CONSTRAINT PK_APPROVAL_LINE PRIMARY KEY (LINE_ID),
    CONSTRAINT FK_APPROVAL_LINE_DOC FOREIGN KEY (DOC_ID) REFERENCES APPROVAL_DOC (DOC_ID)
);
CREATE INDEX IX_APPROVAL_LINE_DOC ON APPROVAL_LINE (DOC_ID, STEP_NO);
CREATE INDEX IX_APPROVAL_LINE_APPROVER ON APPROVAL_LINE (APPROVER_ID, STATUS);

-- 결재 문서 붙임 파일
CREATE SEQUENCE SEQ_APPROVAL_FILE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE APPROVAL_FILE (
    FILE_ID        NUMBER(19)     NOT NULL,
    DOC_ID         NUMBER(19)     NOT NULL,
    ORIGINAL_NAME  VARCHAR2(255)  NOT NULL,
    STORED_NAME    VARCHAR2(100)  NOT NULL,
    FILE_SIZE      NUMBER(19)     NOT NULL,
    CREATED_AT     TIMESTAMP      NOT NULL,
    CONSTRAINT PK_APPROVAL_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_APPROVAL_FILE_DOC FOREIGN KEY (DOC_ID) REFERENCES APPROVAL_DOC (DOC_ID)
);
CREATE INDEX IX_APPROVAL_FILE_DOC ON APPROVAL_FILE (DOC_ID);

-- 출퇴근 기록. 하루에 한 줄 (처음 출근 시각, 마지막 퇴근 시각)
CREATE SEQUENCE SEQ_ATTENDANCE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE ATTENDANCE (
    ATT_ID      NUMBER(19)     NOT NULL,
    LOGIN_ID    VARCHAR2(50)   NOT NULL,
    USER_NAME   VARCHAR2(100)  NOT NULL,
    DEPT_NAME   VARCHAR2(100),
    WORK_DATE   DATE           NOT NULL,
    IN_AT       TIMESTAMP      NOT NULL,
    OUT_AT      TIMESTAMP,
    IN_IP       VARCHAR2(45),
    OUT_IP      VARCHAR2(45),
    CONSTRAINT PK_ATTENDANCE PRIMARY KEY (ATT_ID),
    CONSTRAINT UX_ATTENDANCE_DAY UNIQUE (LOGIN_ID, WORK_DATE)
);
CREATE INDEX IX_ATTENDANCE_DEPT ON ATTENDANCE (DEPT_NAME, WORK_DATE);

-- 선거일·임시공휴일 (관공서의 공휴일에 관한 규정 제2조 제10호의2, 제11호). 법정 공휴일은 프로그램이 계산한다.
CREATE TABLE HOLIDAY_EXTRA (
    HOLIDAY_DATE  DATE           NOT NULL,
    HOLIDAY_NAME  VARCHAR2(100)  NOT NULL,
    CREATED_BY    VARCHAR2(50),
    CREATED_AT    TIMESTAMP,
    CONSTRAINT PK_HOLIDAY_EXTRA PRIMARY KEY (HOLIDAY_DATE)
);

-- 처리과별 연도별 기록물 등록일련번호 (생산·접수 등록번호가 함께 쓴다)
CREATE TABLE DOC_REG_COUNTER (
    DEPT_NAME  VARCHAR2(100)  NOT NULL,
    REG_YEAR   NUMBER(4)      NOT NULL,
    LAST_SEQ   NUMBER(10)     NOT NULL,
    CONSTRAINT PK_DOC_REG_COUNTER PRIMARY KEY (DEPT_NAME, REG_YEAR)
);
