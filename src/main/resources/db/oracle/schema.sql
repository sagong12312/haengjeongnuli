    ROUTE            VARCHAR2(20 CHAR)    NOT NULL,
    APPLICANT_NAME   VARCHAR2(100 CHAR)   NOT NULL,
    MOBILE           VARCHAR2(20 CHAR),
    HOME_PHONE       VARCHAR2(20 CHAR),
    EMAIL            VARCHAR2(200 CHAR),
    ADDRESS          VARCHAR2(500 CHAR),
    NOTIFY_METHOD    VARCHAR2(20 CHAR)    NOT NULL,
    TITLE            VARCHAR2(300 CHAR)   NOT NULL,
    CONTENT          CLOB            NOT NULL,
    DEPT             VARCHAR2(100 CHAR),
    ASSIGNEE         VARCHAR2(100 CHAR),
    STATUS           VARCHAR2(20 CHAR)    NOT NULL,   -- RECEIVED, IN_PROGRESS, DONE
    RECEIVED_AT      TIMESTAMP       NOT NULL,
    DEADLINE         DATE,
    DEADLINE_AT      TIMESTAMP,
    ASSIGNEE_ID      VARCHAR2(50 CHAR),
    PERIOD_DAYS      NUMBER(3),
    EXTEND_COUNT     NUMBER(1)       DEFAULT 0,
    RESULT_TYPE      VARCHAR2(20 CHAR),
    RESULT_TEXT      CLOB,
    REJECT_REMEDY    VARCHAR2(1300 CHAR),
