GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO HJN_OWNER;
CREATE USER HJN_APP IDENTIFIED BY "<프로그램-비밀번호>";
GRANT CREATE SESSION TO HJN_APP;

