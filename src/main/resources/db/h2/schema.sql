-- 로컬(H2, Oracle 호환 모드)용. db/oracle/schema.sql 과 같은 구조이며 여러 번 실행해도 되게 IF NOT EXISTS 를 붙였다.

CREATE SEQUENCE IF NOT EXISTS SEQ_CIVIL_COMPLAINT START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS CIVIL_COMPLAINT (
    COMPLAINT_ID     NUMBER(19)      NOT NULL,
    RECEIPT_NO       VARCHAR2(20)    NOT NULL,
    KIND             VARCHAR2(20)    NOT NULL,
    LAW_INTERPRET_YN CHAR(1)         DEFAULT 'N' NOT NULL,
    LEGAL_AFFAIR     VARCHAR2(40),
    ROUTE            VARCHAR2(20)    NOT NULL,
    APPLICANT_NAME   VARCHAR2(100)   NOT NULL,
    MOBILE           VARCHAR2(20),
    HOME_PHONE       VARCHAR2(20),
    EMAIL            VARCHAR2(200),
    ADDRESS          VARCHAR2(500),
    NOTIFY_METHOD    VARCHAR2(20)    NOT NULL,
    TITLE            VARCHAR2(300)   NOT NULL,
    CONTENT          CLOB            NOT NULL,
    DEPT             VARCHAR2(100),
    ASSIGNEE         VARCHAR2(100),
    STATUS           VARCHAR2(20)    NOT NULL,
    RECEIVED_AT      TIMESTAMP       NOT NULL,
    DEADLINE         DATE,
    COMPLETED_AT     TIMESTAMP,
    REGISTER_ID      VARCHAR2(100)   NOT NULL,
    CONSTRAINT PK_CIVIL_COMPLAINT PRIMARY KEY (COMPLAINT_ID),
    CONSTRAINT UK_CIVIL_RECEIPT_NO UNIQUE (RECEIPT_NO)
);
CREATE INDEX IF NOT EXISTS IX_CIVIL_STATUS_DEADLINE ON CIVIL_COMPLAINT (STATUS, DEADLINE);

CREATE SEQUENCE IF NOT EXISTS SEQ_BOARD_POST START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS BOARD_POST (
    POST_ID      NUMBER(19)     NOT NULL,
    BOARD_TYPE   VARCHAR2(20)   NOT NULL,
    TITLE        VARCHAR2(300)  NOT NULL,
    CONTENT      CLOB,
    CATEGORY     VARCHAR2(50),
    OPEN_SCOPE   VARCHAR2(20)   NOT NULL,
    PINNED_YN    CHAR(1)        DEFAULT 'N' NOT NULL,
    VIEW_COUNT   NUMBER(10)     DEFAULT 0 NOT NULL,
    WRITER       VARCHAR2(100)  NOT NULL,
    WRITER_DEPT  VARCHAR2(100),
    CREATED_AT   TIMESTAMP      NOT NULL,
    WRITER_ID    VARCHAR2(50),
    DELETED_YN   CHAR(1)        DEFAULT 'N' NOT NULL,
    DELETED_AT   TIMESTAMP,
    DELETED_BY   VARCHAR2(50),
    UPDATED_AT   TIMESTAMP,
    UPDATED_BY   VARCHAR2(50),
    CONSTRAINT PK_BOARD_POST PRIMARY KEY (POST_ID)
);
CREATE INDEX IF NOT EXISTS IX_BOARD_TYPE_CREATED ON BOARD_POST (BOARD_TYPE, CREATED_AT);
