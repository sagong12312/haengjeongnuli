CREATE SEQUENCE IF NOT EXISTS SEQ_ATTACH_FILE START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS ATTACH_FILE (
    FILE_ID        NUMBER(19)     NOT NULL,
    POST_ID        NUMBER(19)     NOT NULL,
    ORIGINAL_NAME  VARCHAR2(255)  NOT NULL,
    STORED_NAME    VARCHAR2(100)  NOT NULL,
    FILE_SIZE      NUMBER(19)     NOT NULL,
    DOWNLOAD_COUNT NUMBER(10)     DEFAULT 0 NOT NULL,
    CREATED_AT     TIMESTAMP      NOT NULL,
    CONSTRAINT PK_ATTACH_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_ATTACH_FILE_POST FOREIGN KEY (POST_ID) REFERENCES BOARD_POST (POST_ID)
);
CREATE INDEX IF NOT EXISTS IX_ATTACH_FILE_POST ON ATTACH_FILE (POST_ID);

CREATE SEQUENCE IF NOT EXISTS SEQ_USER_ACCOUNT START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS USER_ACCOUNT (
    USER_ID        NUMBER(19)     NOT NULL,
    LOGIN_ID       VARCHAR2(50)   NOT NULL,
    PASSWORD_HASH  VARCHAR2(200)  NOT NULL,
    USER_NAME      VARCHAR2(100)  NOT NULL,
    POSITION_NAME  VARCHAR2(50),
    DEPT_NAME      VARCHAR2(100),
    ROLE           VARCHAR2(20)   NOT NULL,
    ENABLED_YN     CHAR(1)        DEFAULT 'Y' NOT NULL,
    FAILED_COUNT   NUMBER(3)      DEFAULT 0 NOT NULL,
    LAST_LOGIN_AT  TIMESTAMP,
    CREATED_AT     TIMESTAMP      NOT NULL,
    CONSTRAINT PK_USER_ACCOUNT PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USER_LOGIN_ID UNIQUE (LOGIN_ID)
);

-- 부서 이동 기록
CREATE SEQUENCE IF NOT EXISTS SEQ_USER_DEPT_HISTORY START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS USER_DEPT_HISTORY (
    HISTORY_ID   NUMBER(19)     NOT NULL,
    USER_ID      NUMBER(19)     NOT NULL,
    FROM_DEPT    VARCHAR2(100),
    TO_DEPT      VARCHAR2(100),
    MOVED_AT     TIMESTAMP      NOT NULL,
    MOVED_BY     VARCHAR2(50)   NOT NULL,
    CONSTRAINT PK_USER_DEPT_HISTORY PRIMARY KEY (HISTORY_ID),
    CONSTRAINT FK_DEPT_HISTORY_USER FOREIGN KEY (USER_ID) REFERENCES USER_ACCOUNT (USER_ID)
);

-- 댓글
CREATE SEQUENCE IF NOT EXISTS SEQ_BOARD_COMMENT START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS BOARD_COMMENT (
    COMMENT_ID   NUMBER(19)      NOT NULL,
    POST_ID      NUMBER(19)      NOT NULL,
    CONTENT      VARCHAR2(4000)  NOT NULL,
    WRITER       VARCHAR2(100)   NOT NULL,
    WRITER_ID    VARCHAR2(50)    NOT NULL,
    WRITER_DEPT  VARCHAR2(100),
    CREATED_AT   TIMESTAMP       NOT NULL,
    DELETED_YN   CHAR(1)         DEFAULT 'N' NOT NULL,
    DELETED_AT   TIMESTAMP,
    DELETED_BY   VARCHAR2(50),
    CONSTRAINT PK_BOARD_COMMENT PRIMARY KEY (COMMENT_ID),
    CONSTRAINT FK_COMMENT_POST FOREIGN KEY (POST_ID) REFERENCES BOARD_POST (POST_ID)
);
CREATE INDEX IF NOT EXISTS IX_COMMENT_POST ON BOARD_COMMENT (POST_ID);

-- 접속·작업 기록
CREATE SEQUENCE IF NOT EXISTS SEQ_AUDIT_LOG START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS AUDIT_LOG (
    LOG_ID       NUMBER(19)      NOT NULL,
    OCCURRED_AT  TIMESTAMP       NOT NULL,
    ACTOR_ID     VARCHAR2(50),              -- 로그인 실패 등은 입력한 아이디
    ACTION       VARCHAR2(40)    NOT NULL,
    TARGET       VARCHAR2(200),
    DETAIL       VARCHAR2(1000),
    CLIENT_IP    VARCHAR2(64),
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IF NOT EXISTS IX_AUDIT_TIME ON AUDIT_LOG (OCCURRED_AT);
CREATE INDEX IF NOT EXISTS IX_AUDIT_ACTOR ON AUDIT_LOG (ACTOR_ID, OCCURRED_AT);

-- 알림
CREATE SEQUENCE IF NOT EXISTS SEQ_NOTIFICATION START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS NOTIFICATION (
    NOTI_ID      NUMBER(19)      NOT NULL,
    LOGIN_ID     VARCHAR2(50)    NOT NULL,  -- 받는 사람
    MESSAGE      VARCHAR2(500)   NOT NULL,
    LINK         VARCHAR2(300),
    CREATED_AT   TIMESTAMP       NOT NULL,
    READ_YN      CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_NOTIFICATION PRIMARY KEY (NOTI_ID)
);
CREATE INDEX IF NOT EXISTS IX_NOTI_USER ON NOTIFICATION (LOGIN_ID, READ_YN, CREATED_AT);

