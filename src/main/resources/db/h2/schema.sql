    CONSTRAINT UK_CIVIL_RECEIPT_NO UNIQUE (RECEIPT_NO)
);
CREATE INDEX IF NOT EXISTS IX_CIVIL_STATUS_DEADLINE ON CIVIL_COMPLAINT (STATUS, DEADLINE);

