ALTER TABLE BOARD_POST ADD COLUMN IF NOT EXISTS DELETED_BY VARCHAR2(50);
-- 이전 버전에서 만든 DB에 수정 기능 컬럼 추가
ALTER TABLE BOARD_POST ADD COLUMN IF NOT EXISTS UPDATED_AT TIMESTAMP;
